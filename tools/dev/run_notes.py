"""Generate owner build/play notes from per-task source files (T2337).

Each ``docs/run-notes/T<n>.md`` has three explicitly delimited sections for the
build script, play script, and owner guide. The source files are authoritative;
the marked blocks in those outputs are derived and must not be edited directly.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from tools.agents.taskfiles import write_atomic

NOTE_DIR = Path("docs/run-notes")
HOSTS = {
    "build": Path("tools/dev/build.sh"),
    "play": Path("tools/dev/play.sh"),
    "guide": Path("docs/owner-run-guide.md"),
}
GENERATED_NOTE = "generated by python3 -m tools.dev.run_notes; do not edit"
TASK_FILE = re.compile(r"T([1-9][0-9]*)\.md\Z")
SECTION = re.compile(
    r"<!-- run-notes:(build|play|guide) begin -->\n(.*?)<!-- run-notes:\1 end -->", re.S
)
TASK_COMMENT = re.compile(r"^# (T[1-9][0-9]*)(?:\b|:)")
TASK_TEXT = re.compile(r"^(T[1-9][0-9]*)\b")


class RunNotesError(ValueError):
    """Invalid source note or missing/malformed generated block."""


def markers(target: str) -> tuple[str, str]:
    lead = "# " if target in {"build", "play"} else ""
    detail = f" ({GENERATED_NOTE})"
    return (
        f"{lead}<!-- run-notes:{target} begin{detail} -->",
        f"{lead}<!-- run-notes:{target} end -->",
    )


def load_notes(root: Path) -> dict[str, dict[str, str]]:
    directory = root / NOTE_DIR
    if not directory.exists():
        return {}
    notes: dict[str, dict[str, str]] = {}
    for path in sorted(directory.glob("*.md"), key=lambda p: p.name):
        if not TASK_FILE.fullmatch(path.name):
            raise RunNotesError(f"unexpected file in {NOTE_DIR}: {path.name}")
        task = path.stem
        source = path.read_text()
        if not source.startswith(f"# {task} run notes\n"):
            raise RunNotesError(f"{path}: expected '# {task} run notes' heading")
        sections: dict[str, str] = {}
        cursor = len(f"# {task} run notes\n")
        for match in SECTION.finditer(source, cursor):
            if source[cursor : match.start()].strip():
                raise RunNotesError(f"{path}: unexpected text outside a run-notes section")
            target = match.group(1)
            if target in sections:
                raise RunNotesError(f"{path}: duplicate {target} section")
            content = match.group(2).strip("\n")
            if content and "\r" in content:
                raise RunNotesError(f"{path}: use LF newlines")
            sections[target] = content
            cursor = match.end()
        if source[cursor:].strip():
            raise RunNotesError(f"{path}: malformed or unexpected trailing content")
        if not sections:
            raise RunNotesError(f"{path}: expected at least one run-notes section")
        notes[task] = sections
    return notes


def _all_blocks(text: str, target: str) -> list[re.Match[str]]:
    begin, end = markers(target)
    pattern = re.compile(rf"^{re.escape(begin)}\n.*?^{re.escape(end)}$", re.M | re.S)
    return list(pattern.finditer(text))


def _comment_lines(content: str) -> list[str]:
    return ["# " + line if line else "#" for line in content.splitlines()]


def render_block(target: str, notes: dict[str, dict[str, str]]) -> str:
    lines: list[str] = []
    for task in sorted(notes, key=lambda item: int(item[1:])):
        content = notes[task].get(target, "")
        if not content:
            continue
        if target == "guide":
            if lines:
                lines.append("")
            lines.extend([f"### {task}", "", content])
        else:
            if lines:
                lines.append("#")
            lines.extend(_comment_lines(content))
    begin, end = markers(target)
    return "\n".join([begin, *lines, end])


def rendered(root: Path) -> dict[Path, str]:
    if not (root / NOTE_DIR).exists():
        enabled = any(
            (root / path).exists() and f"run-notes:{target} begin" in (root / path).read_text()
            for target, path in HOSTS.items()
        )
        if enabled:
            raise RunNotesError(f"generated run-note hosts exist but {NOTE_DIR} is missing")
        # Legacy/test trees have not enabled this generated view yet.
        return {}
    notes = load_notes(root)
    result: dict[Path, str] = {}
    for target, path in HOSTS.items():
        host = root / path
        if not host.exists():
            raise RunNotesError(f"missing run-notes host: {path}")
        text = host.read_text()
        blocks = _all_blocks(text, target)
        if len(blocks) != 1:
            raise RunNotesError(f"{path}: expected exactly one run-notes:{target} block")
        begin, end = markers(target)
        body = render_block(target, notes)
        # The fixed marker spelling is validated separately so a hand-edited marker cannot
        # silently turn generated content into ordinary prose.
        if begin not in text or end not in text:
            raise RunNotesError(f"{path}: missing generated run-notes markers")
        result[path] = text[: blocks[0].start()] + body + text[blocks[0].end() :]
    return result


def stale(root: Path) -> list[Path]:
    wanted = rendered(root)
    return [path for path, text in wanted.items() if (root / path).read_text() != text]


def write(root: Path) -> list[Path]:
    wanted = rendered(root)
    changed = [path for path, text in wanted.items() if (root / path).read_text() != text]
    for path in changed:
        write_atomic(root / path, wanted[path])
    return changed


def _note_path(root: Path, task: str) -> Path:
    return root / NOTE_DIR / f"{task}.md"


def _serialize_note(task: str, sections: dict[str, str]) -> str:
    parts = [f"# {task} run notes", ""]
    for target in HOSTS:
        if target not in sections or not sections[target].strip():
            continue
        parts.extend(
            [
                f"<!-- run-notes:{target} begin -->",
                sections[target].strip("\n"),
                f"<!-- run-notes:{target} end -->",
                "",
            ]
        )
    return "\n".join(parts).rstrip() + "\n"


def _content_from_comments(lines: list[str]) -> str:
    return "\n".join(line[2:] if line.startswith("# ") else "" for line in lines)


def _extract_script_comments(root: Path, target: str) -> tuple[str, list[tuple[str, str]]]:
    path = root / HOSTS[target]
    text = path.read_text()
    lines = text.splitlines()
    stop = next((i for i, line in enumerate(lines) if line == "set -eu"), None)
    if stop is None:
        raise RunNotesError(f"{HOSTS[target]}: cannot find preamble boundary 'set -eu'")
    remove: set[int] = set()
    found: list[tuple[str, str]] = []
    i = 0
    generated = False
    while i < stop:
        if f"run-notes:{target} begin" in lines[i]:
            generated = True
            i += 1
            continue
        if f"run-notes:{target} end" in lines[i]:
            generated = False
            i += 1
            continue
        if generated:
            i += 1
            continue
        match = TASK_COMMENT.match(lines[i])
        if not match:
            i += 1
            continue
        task = match.group(1)
        end = i + 1
        while end < stop and lines[end].startswith("# ") and lines[end].strip() != "#":
            if TASK_COMMENT.match(lines[end]):
                break
            if lines[end].startswith("# Paths are relative to the repository root"):
                break
            end += 1
        found.append((task, _content_from_comments(lines[i:end])))
        remove.update(range(i, end))
        i = end
    kept = [line for index, line in enumerate(lines) if index not in remove]
    return "\n".join(kept) + ("\n" if text.endswith("\n") else ""), found


def _extract_guide_paragraphs(root: Path) -> tuple[str, list[tuple[str, str]]]:
    path = root / HOSTS["guide"]
    text = path.read_text()
    lines = text.splitlines()
    remove: set[int] = set()
    found: list[tuple[str, str]] = []
    fenced = False
    in_generated = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if "```" in line:
            fenced = not fenced
        if "<!-- run-notes:guide begin" in line:
            in_generated = True
        if not fenced and not in_generated and (match := TASK_TEXT.match(line)):
            end = i + 1
            while end < len(lines) and lines[end].strip():
                end += 1
            paragraph = "\n".join(lines[i:end])
            # A heading may mention multiple task IDs; preserve the entry for each task.
            ids = list(dict.fromkeys(re.findall(r"\bT[1-9][0-9]*\b", line))) or [match.group(1)]
            found.extend((task, paragraph) for task in ids)
            remove.update(range(i, end))
            i = end
            continue
        if "<!-- run-notes:guide end" in line:
            in_generated = False
        i += 1
    kept: list[str] = []
    blank = False
    for index, line in enumerate(lines):
        if index in remove:
            continue
        if not line.strip():
            if blank:
                continue
            blank = True
        else:
            blank = False
        kept.append(line)
    return "\n".join(kept) + ("\n" if text.endswith("\n") else ""), found


def migrate_existing(root: Path) -> list[Path]:
    """Move task-labelled script preambles and guide paragraphs into task files once."""
    root = root.resolve()
    sources: dict[str, tuple[str, list[tuple[str, str]]]] = {}
    for target in ("build", "play"):
        sources[target] = _extract_script_comments(root, target)
    sources["guide"] = _extract_guide_paragraphs(root)

    by_task: dict[str, dict[str, list[str]]] = {}
    for target, (_, entries) in sources.items():
        for task, content in entries:
            by_task.setdefault(task, {}).setdefault(target, []).append(content)

    directory = root / NOTE_DIR
    directory.mkdir(parents=True, exist_ok=True)
    existing_notes = load_notes(root)
    updated: dict[str, dict[str, str]] = {}
    for task, targets in by_task.items():
        path = _note_path(root, task)
        existing = dict(existing_notes.get(task, {}))
        for target, entries in targets.items():
            if target in existing and existing[target].strip():
                raise RunNotesError(f"{path}: refusing to overwrite existing {target} notes")
            existing[target] = "\n\n".join(entries)
        updated[task] = existing

    for task, sections in updated.items():
        write_atomic(_note_path(root, task), _serialize_note(task, sections))

    changed: list[Path] = []
    for target, (new_text, entries) in sources.items():
        if entries:
            path = root / HOSTS[target]
            if path.read_text() != new_text:
                write_atomic(path, new_text)
                changed.append(HOSTS[target])
    changed.extend(write(root))
    return list(dict.fromkeys(changed))


def collapse_blocks(text: str) -> str:
    """Clear generated run-notes blocks so merge_task can regenerate after conflicts."""
    for target in HOSTS:
        begin, end = markers(target)
        pattern = re.compile(rf"^{re.escape(begin)}\n.*?^{re.escape(end)}$", re.M | re.S)
        text = pattern.sub(f"{begin}\n{end}", text, count=1)
    return text


ABSOLUTE_REPO_PATH = re.compile(r"/workspace/|/mnt/")


def absolute_path_offenders(root: Path) -> list[tuple[Path, int, str]]:
    """Return (file, line number, line) for each absolute repo path in a source note.

    Run notes feed the owner scripts and guide, which must use relative paths only.
    """
    found = []
    for path in sorted((root / NOTE_DIR).glob("T*.md")):
        if not TASK_FILE.fullmatch(path.name):
            continue
        for number, line in enumerate(path.read_text().splitlines(), 1):
            if ABSOLUTE_REPO_PATH.search(line):
                found.append((path.relative_to(root), number, line.strip()))
    return found


def _check(root: Path) -> list[Path]:
    offenders = absolute_path_offenders(root)
    for path, number, line in offenders:
        print(
            f"run_notes: {path}:{number}: absolute repo path (/workspace/ or /mnt/) "
            f"in a run note, use a relative path: {line}",
            file=sys.stderr,
        )
    return stale(root) + list(dict.fromkeys(path for path, _, _ in offenders))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="regenerate the marked blocks")
    action.add_argument("--check", action="store_true", help="fail if generated blocks are stale")
    action.add_argument(
        "--migrate-existing", action="store_true", help="move legacy task notes into per-task files"
    )
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        if args.migrate_existing:
            changed = migrate_existing(root)
        else:
            changed = write(root) if args.write else _check(root)
    except (OSError, RunNotesError) as error:
        print(f"run_notes: {error}", file=sys.stderr)
        return 2
    if changed:
        action_name = (
            "migrated/updated" if args.migrate_existing else "updated" if args.write else "stale"
        )
        print(f"run_notes: {action_name}: " + " ".join(map(str, changed)))
        return 1 if args.check else 0
    print("run_notes: up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
