"""Run the lifted originals of src/game replacements in a capture build (T3794).

In the normal build every src/game registration (`GAME_REPLACE*`) defines `sub_<VA>` strongly and
the lifted definition is made weak (`tools.replace wire`, `#pragma weak` force-included into the
defining chunk). The lifted body, the only one the capture transform brackets with CAP_ENTER, then
never runs: a call to a replaced VA was a call-site frame without a body (a "host callee"), and the
function got zero capture entries however often it ran (0x9A4C0, 3.3 M calls).

This generator inverts the wiring for a capture build only (CMake `TSFP_BUILD_CAPTURE`):
* `<out>/weak_recomp_NNNN.h`: the capture twin of each chunk's game weak header, keeping only the
  symbols whose replacement stays (`tools/data/t2capture_game_originals.json`);
* `<out>/game_<source stem>.h`: `#pragma weak` for the symbols that source defines and gives up, so
  the strong lifted (transformed) definition wins the link;
* `<out>/game_originals.json`: the plan.
The default build never runs this, so it is unchanged.

    python3 -m tools.t2capture.game_originals --game-weak-dir build/game-weak \\
        --game-dir src/game --out-dir build/t2capture-game-weak
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from tools.replace.scan import scan_any_variant, scan_directory

POLICY = Path("tools/data/t2capture_game_originals.json")
INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]+"([^"]+)"', re.M)


class PlanError(ValueError):
    """The inputs disagree; the capture build must stop rather than link half-wired."""


def including_sources(game_dir: Path) -> dict[str, list[str]]:
    """`.inc` name -> the `.c` sources of `game_dir` that include it."""
    users: dict[str, list[str]] = {}
    for path in sorted(game_dir.glob("*.c")):
        for name in INCLUDE.findall(path.read_text(encoding="utf-8")):
            if name.endswith(".inc"):
                users.setdefault(Path(name).name, []).append(path.name)
    return users


def plan(
    wiring: dict[str, list[str]],
    sources: dict[str, str],
    keep_sources: set[str],
    users: dict[str, list[str]],
) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """(chunk -> symbols kept weak in the lifted chunk, game .c source -> symbols made weak there).

    `wiring` is chunk -> weak symbols (`game-weak/wiring.json`), `sources` symbol -> registering
    file (a `.c` or an `.inc`)."""
    chunks: dict[str, list[str]] = {}
    game: dict[str, list[str]] = {}
    for chunk, symbols in sorted(wiring.items()):
        kept = chunks.setdefault(chunk, [])
        for symbol in symbols:
            source = sources.get(symbol)
            if source is None:
                raise PlanError(f"{symbol} is weak in {chunk} but no src/game source registers it")
            if source in keep_sources:
                kept.append(symbol)
                continue
            if source.endswith(".inc"):
                owners = users.get(source, [])
                if len(owners) != 1:
                    raise PlanError(f"{source} is included by {owners or 'no source'}, need one")
                source = owners[0]
            game.setdefault(source, []).append(symbol)
    return chunks, {name: sorted(symbols) for name, symbols in sorted(game.items())}


def header(comment: str, symbols: list[str]) -> str:
    if not symbols:
        return f"/* Generated by tools/t2capture/game_originals.py (T3794). {comment} */\n"
    return "".join(
        [
            f"/* Generated by tools/t2capture/game_originals.py (T3794). {comment} */\n",
            "#pragma clang diagnostic push\n",
            '#pragma clang diagnostic ignored "-Wweak-identifier"\n',
            *(f"#pragma weak {symbol}\n" for symbol in symbols),
            "#pragma clang diagnostic pop\n",
        ]
    )


def write_if_changed(path: Path, text: str) -> None:
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--game-weak-dir", type=Path, required=True, help="tools.replace wire output")
    ap.add_argument("--game-dir", type=Path, default=Path("src/game"))
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--policy", type=Path, default=POLICY)
    ap.add_argument("--define", action="append", default=[], help="TSFP_RUST_GAME_* build define")
    args = ap.parse_args(argv)
    try:
        wiring_path = args.game_weak_dir / "wiring.json"
        if not wiring_path.is_file():
            raise PlanError(f"{wiring_path} missing (run tools.replace wire first)")
        wiring = {
            chunk: list(entry["symbols"])
            for chunk, entry in json.loads(wiring_path.read_text()).items()
        }
        policy = json.loads(args.policy.read_text())
        keep = set(policy["keep_replacement_sources"])
        sources = {reg.symbol: reg.source for reg in scan_any_variant(args.game_dir)}
        unknown = sorted(keep - set(sources.values()))
        if unknown:
            raise PlanError(f"{args.policy}: no registration comes from {unknown}")
        chunks, game = plan(wiring, sources, keep, including_sources(args.game_dir))
    except (PlanError, OSError, KeyError, json.JSONDecodeError) as exc:
        print(f"t2capture game_originals: error: {exc}", file=sys.stderr)
        return 2
    out = args.out_dir
    out.mkdir(parents=True, exist_ok=True)
    expected = set()
    for chunk, kept in chunks.items():
        name = f"weak_{Path(chunk).stem}.h"
        expected.add(name)
        write_if_changed(out / name, header(f"Capture twin of game-weak/{name}.", kept))
    active = {
        registration.symbol
        for registration in scan_directory(args.game_dir, frozenset(args.define))
    }
    for source, symbols in game.items():
        name = f"game_{Path(source).stem}.h"
        expected.add(name)
        declared = [symbol for symbol in symbols if symbol in active]
        write_if_changed(out / name, header(f"{source} yields to the lifted originals.", declared))
    for stale in (*out.glob("weak_recomp_*.h"), *out.glob("game_*.h")):
        if stale.name not in expected:
            stale.unlink()
    originals = sum(len(symbols) for symbols in game.values())
    kept_total = sum(len(symbols) for symbols in chunks.values())
    summary = {
        "schema": 1,
        "lifted_originals": originals,
        "kept_replacements": kept_total,
        "game_headers": {source: f"game_{Path(source).stem}.h" for source in game},
    }
    write_if_changed(out / "game_originals.json", json.dumps(summary, indent=1) + "\n")
    print(f"{originals} lifted originals, {kept_total} replacements kept")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
