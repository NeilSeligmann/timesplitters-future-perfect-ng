"""T3871: build and run the per-function equivalence harnesses.

For a VA the runner writes, under a scratch work dir (`tmp/t2symbolic/<crate>/`, never committed):

- `glue.c` (symbolic memory) and `glue_fuzz.c` (page memory) from `templates/glue.c` with the
  lifted body pasted in, next to links to the lift's headers (Kani's `--c-lib` has no `-I`);
- a harness crate (`templates/harness.rs`, `Cargo.toml`) depending on the port crate by path,
  one `#[kani::proof]` per VA and one `t2s_fuzz_one` entry for libFuzzer.

`symbolic` runs `cargo kani -Z c-ffi --c-lib glue.c --harness <va>` and maps the result to a
verdict (`verdict.classify`); `fuzz` (`tools.t2symbolic.fuzz`) builds the libFuzzer binary.
Every external command carries a timeout.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import signal
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path

from tools.t2symbolic import limits, rewrite, verdict
from tools.t2symbolic.inventory import ROOT, Row, parse_lifted

TEMPLATES = Path(__file__).resolve().parent / "templates"
WORK = Path("tmp/t2symbolic")
CLEAN_VERDICTS = frozenset({verdict.PROVED_EQUAL})
# CBMC unwinding bound: loops in either body are unrolled this far, with unwinding assertions on,
# so a loop that can run longer is reported as `bound_exceeded`, never silently cut.
DEFAULT_UNWIND = 34
# The harness itself loops (register pairs, argument words, byte-wise accesses): never below this.
HARNESS_MIN_UNWIND = 12
DEFAULT_TIMEOUT = 600
KANI_HOME_DIR = Path("tmp/tools/kani/home")
KANI_BIN_DIR = Path("tmp/tools/kani/bin-root/bin")


@dataclass(frozen=True)
class Case:
    va: int
    function: str
    module_path: str
    pops: int
    fpo_leaf: bool

    @property
    def harness(self) -> str:
        return f"t2s_{self.va:08x}"


def crate_ident(crate: str) -> str:
    return crate.replace("-", "_")


def module_path(row: Row) -> str:
    """`tsfp-port-x/c2r/mod` -> `tsfp_port_x::c2r::mod` (the registry's module form)."""
    assert row.rust is not None
    crate, _, rest = row.rust.module.partition("/")
    parts = [crate_ident(crate)] + [part for part in rest.split("/") if part and part != "lib"]
    return "::".join(parts)


def case_of(row: Row) -> Case:
    assert row.rust is not None and row.ret_pops is not None
    return Case(row.va, row.rust.function, module_path(row), row.ret_pops, row.fpo_leaf)


def render_glue(bodies: list[str], vas: list[int], symbolic: bool) -> str:
    """The C side; `symbolic` selects the CBMC flat-array memory, else the fuzz page model."""
    template = (TEMPLATES / "glue.c").read_text()
    dispatch = "\n".join(f"    case {va:#x}u: sub_{va:08X}(); break;" for va in vas)
    text = template.replace("@BODIES@", "\n\n".join(bodies)).replace("@DISPATCH@", dispatch)
    return ("#define T2S_SYMBOLIC 1\n" if symbolic else "") + text


def render_harness(cases: list[Case], unwind: int) -> str:
    template = (TEMPLATES / "harness.rs").read_text()
    table = "\n".join(
        f"    Case {{ va: {c.va:#x}, pops: {c.pops}, fpo_leaf: {str(c.fpo_leaf).lower()}, "
        f"port: |m, r| {c.module_path}::{c.function}(m, r) }},"
        for c in cases
    )
    proofs = "\n".join(
        f"    #[kani::proof]\n    #[kani::unwind({max(unwind, HARNESS_MIN_UNWIND)})]\n"
        f"    fn {c.harness}() {{\n"
        f"        check(case({c.va:#x}));\n    }}"
        for c in cases
    )
    return template.replace("    // @CASES@", table).replace("    // @PROOFS@", proofs)


def render_manifest(crate: str, crate_dir: Path, runtime_dir: Path) -> str:
    return (
        "# Generated by tools.t2symbolic (T3871); scratch, never committed.\n"
        "[package]\n"
        f'name = "t2s-harness-{crate}"\n'
        'version = "0.0.0"\n'
        'edition = "2024"\n'
        "publish = false\n\n"
        "[lib]\n"
        'path = "lib.rs"\n'
        'crate-type = ["rlib"]\n\n'
        "[dependencies]\n"
        f'{crate} = {{ path = "{crate_dir}" }}\n'
        f'tsfp-port-runtime = {{ path = "{runtime_dir}" }}\n\n'
        "[workspace]\n\n"
        "[lints.rust]\n"
        "unexpected_cfgs = { level = \"allow\", check-cfg = ['cfg(kani)'] }\n"
    )


def link_headers(gen_dir: Path, out: Path) -> None:
    """Kani's `--c-lib` takes no include path, so the lift's headers sit next to glue.c (links)."""
    headers = sorted([*gen_dir.glob("*.h"), *gen_dir.glob("*.inc")])
    if not headers:
        raise FileNotFoundError(f"no headers in {gen_dir}")
    for header in headers:
        link = out / header.name
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to(header.resolve())


def kani_env(target_dir: Path, root: Path = ROOT) -> dict[str, str]:
    env = dict(os.environ)
    env["KANI_HOME"] = str(root / KANI_HOME_DIR)
    env["PATH"] = f"{root / KANI_BIN_DIR}{os.pathsep}{env.get('PATH', '')}"
    env["CARGO_TARGET_DIR"] = str(target_dir)
    return env


def run_bounded(
    command: list[str],
    timeout: int,
    env: dict[str, str] | None,
    cwd: Path,
    memory: int = limits.MEMORY_LIMIT_BYTES,
) -> tuple[str, bool]:
    """Run in its own process group under the host limits (`limits`): one solver slot, an
    address-space cap on the whole tree, peak RSS printed by GNU time. On timeout kill the whole
    group (cargo, kani, cbmc), so nothing outlives the run."""
    with limits.slot(kani_root() / limits.SLOT_DIR):
        proc = subprocess.Popen(
            limits.measured(command),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            env=env,
            cwd=cwd,
            start_new_session=True,
            preexec_fn=limits.limit_memory(memory),
        )
        try:
            output, _ = proc.communicate(timeout=timeout)
            return output, False
        except subprocess.TimeoutExpired:
            os.killpg(proc.pid, signal.SIGKILL)
            output, _ = proc.communicate()
            return output or "", True


def kani_root(root: Path = ROOT) -> Path:
    """Kani installs once per host into the main checkout's tmp (`tools.private_host`)."""
    if (root / KANI_BIN_DIR / "cargo-kani").exists():
        return root
    from tools import private_host

    return private_host.main_checkout(root, None)


def kani_version(root: Path = ROOT) -> str | None:
    """`cargo kani --version` (e.g. "cargo-kani 0.68.0"), None when Kani is not installed."""
    try:
        done = subprocess.run(
            ["cargo", "kani", "--version"], env=kani_env(Path("/dev/null"), kani_root(root)),
            capture_output=True, text=True, timeout=180, check=False,
        )  # fmt: skip
    except (OSError, subprocess.TimeoutExpired):
        return None
    return done.stdout.strip() or None if done.returncode == 0 else None


def prepare(
    rows: list[Row],
    gen_dir: Path,
    work: Path,
    unwind: int = DEFAULT_UNWIND,
    crates_root: Path = ROOT / "crates",
) -> tuple[Path, list[Case]]:
    """Write the glue and harness crate for rows of one crate; returns (dir, cases)."""
    crates = {row.rust.crate for row in rows if row.rust is not None}
    if len(crates) != 1:
        raise ValueError(f"one crate per harness, got {sorted(crates)}")
    crate = crates.pop()
    lifted = parse_lifted(gen_dir)
    cases = [case_of(row) for row in rows]
    helpers = rewrite.memory_helpers((gen_dir / "recomp_types.h").read_text(errors="replace"))
    bodies = []
    for c in cases:
        rewrite.refuse_unmodelled_helpers(lifted[c.va].body, helpers)
        body = rewrite.functionalise(lifted[c.va].body)
        bodies.append(f"void sub_{c.va:08X}(void)\n{{\n{body}}}")
    out = work / crate
    out.mkdir(parents=True, exist_ok=True)
    vas = [c.va for c in cases]
    (out / "glue.c").write_text(render_glue(bodies, vas, symbolic=True))
    (out / "glue_fuzz.c").write_text(render_glue(bodies, vas, symbolic=False))
    link_headers(gen_dir, out)
    (out / "lib.rs").write_text(render_harness(cases, unwind))
    (out / "Cargo.toml").write_text(
        render_manifest(crate, crates_root / crate, ROOT / "crates" / "tsfp-port-runtime")
    )
    return out, cases


def run_kani(
    harness_dir: Path, case: Case, timeout: int, playback: bool = False
) -> dict[str, object]:
    command = [
        "cargo",
        "kani",
        "--manifest-path",
        str(harness_dir / "Cargo.toml"),
        "-Z",
        "c-ffi",
        "--c-lib",
        str(harness_dir / "glue.c"),
        "--harness",
        f"proofs::{case.harness}",
        "--exact",
    ]
    if playback:
        command += ["-Z", "concrete-playback", "--concrete-playback=print"]
    # One target dir per port crate, shared by every VA of that crate (the crate builds once).
    target = harness_dir.parent.parent / "target" / harness_dir.name
    started = time.monotonic()
    output, timed_out = run_bounded(command, timeout, kani_env(target, kani_root()), harness_dir)
    seconds = time.monotonic() - started
    (harness_dir / f"{case.harness}.log").write_text(output)
    result = verdict.classify(output, timed_out)
    if result["verdict"] == verdict.UNSUPPORTED and limits.out_of_memory(output):
        result = {"verdict": verdict.TIMEOUT, "reason": "out of memory under the 6 GB cap"}
    result["seconds"] = round(seconds, 2)
    result["peak_rss_mb"] = limits.peak_rss_mb(output)
    result["log"] = str(harness_dir / f"{case.harness}.log")
    return result


def add_run_options(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--work", type=Path, default=WORK, help="scratch dir for generated harnesses"
    )
    parser.add_argument("--unwind", type=int, default=DEFAULT_UNWIND)
    parser.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT, help="seconds per function")
    parser.add_argument(
        "--fuzz", type=int, default=0, help="also fuzz this many seconds (libFuzzer)"
    )


def check(
    row: Row,
    gen_dir: Path,
    args: argparse.Namespace,
    fuzz_seconds: int = 0,
    crates_root: Path = ROOT / "crates",
) -> dict[str, object]:
    """Symbolic verdict (and, with `fuzz_seconds`, a libFuzzer verdict) for one eligible leaf."""
    assert row.rust is not None
    record: dict[str, object] = {
        "va": f"{row.va:#x}",
        "name": row.name,
        "subsystem": row.subsystem,
        "crate": row.rust.crate,
        "function": row.rust.function,
        "loops": row.c_loops,
    }
    work = args.work.resolve() / f"{row.va:08x}"
    if work.exists():
        shutil.rmtree(work)
    try:
        harness_dir, cases = prepare([row], gen_dir, work, args.unwind, crates_root)
    except (subprocess.CalledProcessError, KeyError, ValueError, FileNotFoundError) as error:
        detail = getattr(error, "stderr", "") or str(error)
        record["symbolic"] = {
            "verdict": verdict.UNSUPPORTED,
            "reason": f"harness: {detail[:300]}",
            "seconds": 0.0,
        }
        return record
    result = run_kani(harness_dir, cases[0], args.timeout)
    if result["verdict"] == verdict.COUNTEREXAMPLE:
        replay = run_kani(harness_dir, cases[0], args.timeout, playback=True)
        result["input"] = verdict.playback_values(Path(str(replay["log"])).read_text())
    record["symbolic"] = result
    if fuzz_seconds:
        from tools.t2symbolic import fuzz

        record["fuzz"] = fuzz.run(harness_dir, cases[0], fuzz_seconds)
    return record


def ineligible(row: Row) -> dict[str, object]:
    """Verdict record for a row the harness cannot call (not in its module's `run` table, or
    unknown RET pops): reported as `unsupported`, never skipped silently."""
    why = "not in the module run table" if row.ret_pops is not None else "unknown RET pops"
    return {
        "va": f"{row.va:#x}",
        "name": row.name,
        "subsystem": row.subsystem,
        "crate": row.rust.crate if row.rust else "",
        "loops": row.c_loops,
        "symbolic": {
            "verdict": verdict.UNSUPPORTED,
            "reason": f"ineligible: {why}",
            "seconds": 0.0,
        },
    }


def to_json(record: dict[str, object]) -> str:
    return json.dumps(record, sort_keys=True)
