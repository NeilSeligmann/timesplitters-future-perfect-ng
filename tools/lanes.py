MANIFEST = "crates/tsfp-ports/lanes.json"
INPUTS = [MANIFEST]
# T3765: c2r lane roots live in a leaf crate (tsfp-ports is frozen, AGENTS.md rule 37). A lane with
# `"crate": C2R_CRATE` has no hand-written module; each row names its c2r owner as
# `<family crate>/<module path under src/c2r>` and the crate's dispatch and exports are generated.
C2R_CRATE = "tsfp-lane-c2r"
C2R_LIB = f"crates/{C2R_CRATE}/src/lib.rs"
C2R_CARGO = f"crates/{C2R_CRATE}/Cargo.toml"
C2R_OWNER = re.compile(r"(tsfp-[a-z0-9-]+)/([a-z][a-z0-9_]*(?:/[a-z][a-z0-9_]*)*)")
# A root whose `run` arm lives in a tsfp-ports facade module names the translated function the
# facade calls (`c2r_call`), with the facade's own argument names.
C2R_CALL = re.compile(r"[a-z_][a-z0-9_]*\((?:m|guest|regs)(?:, (?:m|guest|regs))*\)")
OUTPUTS = [
    "crates/tsfp-ports/src/lane_inv.rs",
    "src/host/rust_lane_roots.h",
    "tools/replace/invpose_roots.json",
    "crates/tsfp-ports/tests/runtime.rs",
    "crates/tsfp-ports/src/runtime.rs",
    "crates/tsfp-ports/src/lib.rs",
    C2R_LIB,
    C2R_CARGO,
]
MIGRATION_OUTPUTS = OUTPUTS[:6]  # the pinned T2221 proof predates the c2r lane crate
# Every Rust output is passed through rustfmt (T2122), so the parsers below accept both the
# raw emitter layout and rustfmt's (wrapped arrays, `#[path]` on its own line).
ROOT_TABLE = re.compile(r"pub const INV_ROOTS: \[u32; \d+\] = \[.*?\];", re.S)
DISPATCH = re.compile(r"const MODULES: u8 = \d+;.*?\n}\n", re.S)
TEST_MODULE = re.compile(r'#\[path = "([^"]+)"\]\s*mod (\w+);')
LIB_MODULE = re.compile(r'(?:#\[path = "([^"]+)"\]\s*)?(?:pub )?mod (\w+);')
BEGIN = "/* ---- TSFP_INV_ROOTS begin (generated by tools/replace/gen_invpose_host.py) ---- */\n"
END = "/* ---- TSFP_INV_ROOTS end ---- */\n"
FIELDS = ("va", "module", "ret_pops", "stack_args", "calls", "x87", "sse")


def replace_once(pattern: re.Pattern, replacement: str, text: str) -> str:
    result, count = pattern.subn(lambda _: replacement, text)
    if count != 1:
        raise ValueError(f"expected one generated region: {pattern.pattern}")
    return result


def rustfmt(root: Path, text: str) -> str:
    """Format one generated Rust file the way `cargo fmt` does, so the fmt check agrees."""
    from tools.wt import core

    # `root` is often a disposable generated-output fixture. Use this module's checkout
    # to select the shared Rust home, while keeping rustfmt's working directory at `root`.
    core.apply_rust_env(Path(__file__).resolve().parents[1])
    result = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout", "--quiet"],
        cwd=root,
        input=text,
        capture_output=True,
        text=True,
        timeout=120,
    )
    if result.returncode:
        raise ValueError(f"rustfmt failed: {result.stderr.strip()[-300:]}")
    return result.stdout


def load(root: Path) -> tuple[dict, list[dict], list[dict]]:
    manifest = json.loads((root / MANIFEST).read_text())
    if manifest["schema"] != 1:
        raise ValueError("unsupported lane manifest schema")
    modules, addresses, rows = set(), set(), []
    for lane in manifest["lanes"]:
        module = lane["module"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", module):
            raise ValueError(f"invalid module {module}")
        if module in modules:
            raise ValueError(f"duplicate module {module}")
        modules.add(module)
        external = "crate" in lane
        if external and lane["crate"] != C2R_CRATE:
            raise ValueError(f"lane {module}: unsupported lane crate {lane['crate']}")
        if not external and not (root / f"crates/tsfp-ports/src/{module}.rs").is_file():
            raise ValueError(f"missing lane module {module}")
        for record in lane["roots"]:
            row = dict(record, module=module)
            owner = row.get("c2r")
            if external != (owner is not None):
                raise ValueError(f"root {row['va']}: c2r owner only and always on {C2R_CRATE}")
            if external and (not C2R_OWNER.fullmatch(owner) or owner.startswith("tsfp-ports/")):
                raise ValueError(f"root {row['va']}: invalid c2r owner {owner}")
            call = row.get("c2r_call")
            if call is not None and (not external or not C2R_CALL.fullmatch(call)):
                raise ValueError(f"root {row['va']}: invalid c2r_call {call}")
            if not re.fullmatch(r"[0-9A-F]{8}", row["va"]) or int(row["va"], 16) == 0:
                raise ValueError("invalid root address")
            if row["va"] in addresses:
                raise ValueError(f"duplicate root {row['va']}")
            addresses.add(row["va"])
            if type(row["stack_args"]) is not int or row["stack_args"] < 0:
                raise ValueError("invalid stack_args")
            pops = row["ret_pops"]
            if not isinstance(pops, list) or any(
                type(n) is not int or n < 0 or n % 4 for n in pops
            ):
                raise ValueError("invalid ret_pops")
            if any(type(row[field]) is not bool for field in ("calls", "x87", "sse")):
                raise ValueError("invalid state metadata")
            if type(row.get("selectable", True)) is not bool:
                raise ValueError("invalid selectable flag")
            rows.append(row)
    for field in ("metadata_order", "selector_order"):
        orders = [row[field] for row in rows if field in row]
        if any(type(n) is not int or n < 0 for n in orders) or len(set(orders)) != len(orders):
            raise ValueError(f"duplicate or invalid {field}")
    metadata_tail = max((row.get("metadata_order", -1) for row in rows), default=-1) + 1
    selector_tail = max((row.get("selector_order", -1) for row in rows), default=-1) + 1
    metadata = sorted(rows, key=lambda row: row.get("metadata_order", metadata_tail))
    selected = sorted(
        (row for row in rows if row.get("selectable", True)),
        key=lambda row: row.get("selector_order", selector_tail),
    )
    host_addresses = set()
    for label, group in manifest["legacy"].items():
        seen = set()
        for row in group["roots"]:
            va = row["va"]
            if not re.fullmatch(r"[0-9A-F]{8}", va) or int(va, 16) == 0 or va in seen:
                raise ValueError(f"invalid or duplicate legacy root in {label}")
            seen.add(va)
            if label == "LANE_ROOTS" and (type(row["pops"]) is not int or row["pops"] < 0):
                raise ValueError("invalid legacy cleanup")
        if label in ("LANE_ROOTS", "HOST_ROOTS"):
            if seen & host_addresses:
                raise ValueError("duplicate host selector root")
            host_addresses.update(seen)
    if host_addresses & {row["va"] for row in selected}:
        raise ValueError("duplicate host selector root")
    if len(host_addresses) + len(selected) >= 65535:
        raise ValueError("root map supports fewer than 65535 roots")
    if len(modules) > 255:
        raise ValueError("handler cache supports at most 255 modules")
    return manifest, metadata, selected


def root_table(manifest: dict, rows: list[dict]) -> str:
    values = [f"0x{int(row['va'], 16):x}" for row in rows]
    lines, at = [], 0
    # Retain historical grouping/comments so the initial migration is byte identical.
    # New roots need no formatting metadata and are emitted eight per line.
    for group in manifest["migration_layout"]:
        if "comment" in group:
            lines.append("    // " + group["comment"])
        else:
            count = group["count"]
            if count <= 0:
                raise ValueError("invalid migration row width")
            if at < len(values):
                lines.append("    " + ", ".join(values[at : at + count]) + ",")
            at += count
    for index in range(at, len(values), 8):
        lines.append("    " + ", ".join(values[index : index + 8]) + ",")
    return f"pub const INV_ROOTS: [u32; {len(rows)}] = [\n" + "\n".join(lines) + "\n];"


def test_modules(manifest: dict, lib: str, text: str, root: Path, *, discover: bool = True) -> str:
    paths = {name: path or None for path, name in LIB_MODULE.findall(lib)}
    # The test root may already import a sibling module under its crate-root name. In
    # that case a path module would declare the same name and shadow the intended import.
    imported_external = set()
    for module, alias in re.findall(
        r"(?:pub(?:\([^)]*\))?\s+)?use\s+tsfp_[A-Za-z0-9_]+::"
        r"([A-Za-z_][A-Za-z0-9_]*)(?:\s+as\s+([A-Za-z_][A-Za-z0-9_]*))?;",
        text,
    ):
        imported_external.add(alias or module)
    # Integration tests compile the lifted C2R sources directly under their own crate root.
    # Preserve simple public module re-exports from sibling family crates there too, since
    # C2R callers may address them through `crate::<module>` just like lib.rs does.
    for dependency, module in re.findall(
        r"pub\s+use\s+(tsfp_[A-Za-z0-9_]+)::([A-Za-z_][A-Za-z0-9_]*);", lib
    ):
        external = root / "crates" / dependency.replace("_", "-") / "src" / f"{module}.rs"
        if external.is_file() and module not in imported_external:
            paths.setdefault(module, f"../../{dependency.replace('_', '-')}/src/{module}.rs")
    # T3484: state_wire is shared in tsfp-port-runtime (lib.rs re-exports it).
    if discover and not paths.get("state_wire"):
        paths["state_wire"] = "../../tsfp-port-runtime/src/state_wire.rs"
    names = list(manifest["runtime_modules"])
    for lane in manifest["lanes"]:
        if "crate" not in lane and lane["module"] not in names:
            names.insert(names.index("runtime"), lane["module"])
    if len(set(names)) != len(names):
        raise ValueError("duplicate runtime test module")
    # Discover transitive root-level source dependencies; adding a lane never needs
    # a second hand-maintained harness module entry. The seed order is migration-only.
    inline = set(re.findall(r"(?:pub )?mod (\w+) \{", text))
    for name in names if discover else []:
        path = paths.get(name)
        if path is None:
            source = root / f"crates/tsfp-ports/src/{name}.rs"
            if not source.exists():
                source = root / f"crates/tsfp-ports/src/{name}/mod.rs"
        else:
            source = root / "crates/tsfp-ports/src" / path
        if not source.exists():
            continue  # External paths are pinned by lib.rs, checked by cargo.
        source_text = source.read_text()
        if source.name == "mod.rs":
            # The old harness guard stopped at a module directory. Its children
            # may call root-level modules too (T2049's manual action/link adapters).
            source_text += "\n" + "\n".join(
                child.read_text()
                for child in sorted(source.parent.rglob("*.rs"))
                if child != source
            )
        dependencies = set(re.findall(r"\bcrate::(\w+)", source_text))
        for group in re.findall(r"use\s+crate::\{(.*?)\};", source_text, re.S):
            dependencies.update(
                re.findall(r"(?:^|[,{])\s*(\w+)(?:\s+as\s+\w+)?\s*(?=::|[,}])", group)
            )
        for dependency in sorted(dependencies - set(names) - inline):
            if dependency in paths:
                names.append(dependency)
    declarations = []
    for name in names:
        path = paths.get(name)
        if path is None:
            source = root / f"crates/tsfp-ports/src/{name}"
            if source.with_suffix(".rs").exists():
                path = f"{name}.rs"
            elif (source / "mod.rs").exists():
                path = f"{name}/mod.rs"
            elif name == "state_wire":
                path = "state_wire.rs"  # pinned historic layout (migration parity only)
            else:
                raise ValueError(f"missing runtime test module {name}")
        if not path.startswith("../../"):
            path = "../src/" + path
        declarations.append(f'#[path = "{path}"] mod {name};')
    matches = list(TEST_MODULE.finditer(text))
    if not matches:
        raise ValueError("missing runtime test module region")
    at = 0

    def emit(_: re.Match) -> str:
        nonlocal at
        line = declarations[at] if at < len(declarations) else ""
        at += 1
        if at == len(matches) and at < len(declarations):
            line += "\n" + "\n".join(declarations[at:])
        return line

    return TEST_MODULE.sub(emit, text)


