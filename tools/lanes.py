def c2r_crate(rows: list[dict]) -> tuple[str, str]:
    """The generated lib.rs and Cargo.toml of the c2r lane crate for `rows` (selector order)."""
    owners: dict[str, list[int]] = {}
    calls: list[tuple[str, int, str]] = []
    for row in rows:
        if "c2r_call" in row:
            calls.append((row["c2r"], int(row["va"], 16), row["c2r_call"]))
        else:
            owners.setdefault(row["c2r"], []).append(int(row["va"], 16))
    values = [f"0x{int(row['va'], 16):x}" for row in rows]

    def module_path(owner: str) -> str:
        crate, module = C2R_OWNER.fullmatch(owner).groups()
        return crate.replace("-", "_") + "::c2r::" + module.replace("/", "::")

    # The lane dispatches to its owners, it is no second port (tools.portreg duplicate check).
    mirrors = sorted(
        {
            f"{crate}/c2r/{module}"
            for crate, module in (C2R_OWNER.fullmatch(row["c2r"]).groups() for row in rows)
        }
    )
    text = C2R_HEADER.replace(
        "\n", "\n" + "".join(f"// portreg: mirrors={owner}\n" for owner in mirrors), 1
    )
    text += f"\npub const ROOTS: [u32; {len(rows)}] = [{', '.join(values)}];\n\n"
    text += (
        "/// Runs a c2r lane root; `false` when `va` is not one.\n"
        "pub fn run<M: GuestMemory, C: GuestCall>(va: u32, m: &mut M, guest: &mut C, "
        "regs: &mut ExtRegisters) -> bool {\n    let entry_esp = regs.esp;\n"
        "    let handled = match va {\n"
    )
    for owner, vas in owners.items():
        text += (
            f"        {' | '.join(f'0x{va:x}' for va in vas)} => guarded(va, m, guest, regs, "
            f"|view, guest, regs| {module_path(owner)}::run(va, view, guest, regs)),\n"
        )
    for owner, va, call in calls:
        used = re.findall(r"\w+", call.split("(", 1)[1])
        params = ", ".join(name if name in used else "_" for name in ("m", "guest", "regs"))
        text += (
            f"        0x{va:x} => guarded(va, m, guest, regs, |{params}| "
            f"{{ {module_path(owner)}::{call}; true }}),\n"
        )
    text += "        _ => return false,\n    };\n    regs.esp = entry_esp;\n    handled\n}\n\n"
    text += (
        'unsafe extern "C" {\n'
        "    fn tsfp_lane_c2r_execute(va: u32, cpu: *mut core::ffi::c_void, offset: usize);\n}\n\n"
        "macro_rules! export {\n    ($name:ident, $va:expr) => {\n"
        "        /// # Safety\n"
        "        /// `cpu` is a live C rust_cpu object and offset maps the guest window.\n"
        "        #[unsafe(no_mangle)]\n"
        '        pub unsafe extern "C" fn $name(cpu: *mut core::ffi::c_void, offset: usize) {\n'
        "            unsafe { tsfp_lane_c2r_execute($va, cpu, offset) }\n        }\n    };\n}\n"
        "\n/// T3765: lane-guard events so far (degraded runs, skipped callees, rollbacks to the\n"
        "/// original). The offline Tier 2 host refuses a port run that moved this count.\n"
        "#[unsafe(no_mangle)]\n"
        'pub extern "C" fn tsfp_lane_guard_events() -> u64 {\n'
        "    let (degraded, skipped, rolled_back) =\n"
        "        tsfp_port_engine_anim_adapter::anim_lane::guard_counters();\n"
        "    u64::from(degraded) + u64::from(skipped) + u64::from(rolled_back)\n}\n\n"
    )
    text += "".join(
        f"export!(tsfp_lane_{int(row['va'], 16):08x}, {value});\n"
        for row, value in zip(rows, values, strict=True)
    )
    crates = sorted({C2R_OWNER.fullmatch(row["c2r"])[1] for row in rows})
    base = ["tsfp-port-engine-anim-adapter", "tsfp-port-runtime"]
    dependencies = "".join(
        f'{crate} = {{ path = "../{crate}" }}\n' for crate in sorted({*base, *crates})
    )
    return text, C2R_CARGO_TEXT.format(name=C2R_CRATE, dependencies=dependencies)


def generate(root: Path, *, migration_only: bool = False) -> dict[str, str]:
    manifest, metadata, selected = load(root)
    names = MIGRATION_OUTPUTS if migration_only else OUTPUTS
    output = {name: (root / name).read_text() for name in names}
    external = {lane["module"] for lane in manifest["lanes"] if "crate" in lane}
    c2r_rows = [row for row in selected if row["module"] in external]
    # tsfp-ports lists its own roots; runtime.rs appends tsfp_lane_c2r::ROOTS after them.
    local = [row for row in selected if row["module"] not in external]
    name = OUTPUTS[0]
    output[name] = replace_once(ROOT_TABLE, root_table(manifest, local), output[name])
    modules = [lane["module"] for lane in manifest["lanes"]]
    crate_path = C2R_CRATE.replace("-", "_")
    dispatch = f"const MODULES: u8 = {len(modules)};\n\n"
    dispatch += (
        "fn run_module(id: u8, va: u32, m: &mut MappedGuest, guest: &mut LaneGuest, "
        "regs: &mut ExtRegisters) -> bool {\n    match id {\n"
    )
    dispatch += "".join(
        f"        {i} => {crate_path if module in external else 'crate::' + module}::run"
        "(va, m, guest, regs),\n"
        for i, module in enumerate(modules)
    )
    if not migration_only:
        output[C2R_LIB], output[C2R_CARGO] = c2r_crate(c2r_rows)
    dispatch += "        _ => false,\n    }\n}\n"
    output[name] = replace_once(DISPATCH, dispatch, output[name])
    clean = [{field: row[field] for field in FIELDS} for row in metadata]
    output[OUTPUTS[2]] = json.dumps({"schema": 1, "roots": clean}, indent=1) + "\n"
    # Metadata order is the historical C macro order; selector order is independent.
    host = [row for row in metadata if row.get("selectable", True)]
    rows = []
    for row in host:
        # Same convention rule as rust_lane.inv_registration: nonzero RET cleanup
        # uses stack_args as the stdcall cleanup count, not the raw byte value.
        cleanup = row["ret_pops"]
        pops = (
            min(max(row["stack_args"], max(cleanup, default=0) // 4), 8)
            if cleanup and cleanup[0] > 0
            else 0
        )
        rows.append(f"    X({row['va'].lower()}, {pops})")
    block = BEGIN + "#define TSFP_INV_ROOTS(X) \\\n" + " \\\n".join(rows) + "\n" + END
    output[OUTPUTS[1]] = replace_once(
        re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S), block, output[OUTPUTS[1]]
    )
    lib = output[OUTPUTS[5]]
    declarations = LIB_MODULE.findall(lib)
    declared = {name for _, name in declarations}
    if len(declarations) != len(declared):
        raise ValueError("duplicate library module")
    for module in modules:
        if module in external:
            continue
        if module in declared:
            lib = re.sub(
                rf'(?:#\[path = "[^\"]+"\]\s*)?pub mod {module};',
                f"pub mod {module};",
                lib,
            )
        else:
            lib += f"pub mod {module};\n"
    output[OUTPUTS[5]] = lib
    output[OUTPUTS[3]] = test_modules(
        manifest, lib, output[OUTPUTS[3]], root, discover=not migration_only
    )
    runtime = output[OUTPUTS[4]]
    base = 0
    for label in ("LANE_ROOTS", "HOST_ROOTS"):
        group = manifest["legacy"][label]
        root_rows = group["roots"]
        table = root_table(
            {"migration_layout": [{"count": count} for count in group["row_widths"]]},
            root_rows,
        ).replace("INV_ROOTS", label)
        runtime = replace_once(
            re.compile(rf"pub const {label}: \[u32; \d+\] = \[.*?\];", re.S),
            table,
            runtime,
        )
        base += len(root_rows)
    legacy_rows = [
        f"    X({row['va'].lower()}, {row['pops']})"
        for row in manifest["legacy"]["LANE_ROOTS"]["roots"]
    ]
    legacy_block = "#define TSFP_LANE_ROOTS(X) \\\n" + " \\\n".join(legacy_rows) + "\n"
    output[OUTPUTS[1]] = replace_once(
        re.compile(r"#define TSFP_LANE_ROOTS\(X\).*?(?=/\* ---- TSFP_INV_ROOTS begin)", re.S),
        legacy_block,
        output[OUTPUTS[1]],
    )
    total = base + len(selected)
    runtime = replace_once(
        re.compile(r"pub const WORDS: usize = \d+;"),
        f"pub const WORDS: usize = {(total + 63) // 64};",
        runtime,
    )
    capacity = 1 << (max(2, total * 2) - 1).bit_length()
    runtime = replace_once(
        re.compile(r"pub static ROOT_MAP: crate::rootmap::RootMap<\d+>"),
        f"pub static ROOT_MAP: crate::rootmap::RootMap<{capacity}>",
        runtime,
    )
    output[OUTPUTS[4]] = runtime
    if not migration_only:
        output[OUTPUTS[3]] = replace_once(
            re.compile(
                r"assert_eq!\(\s*runtime::ROOTS.len\(\),\s*(?:"
                r"\d+\s*\+\s*\d+\s*\+\s*\d+|"
                r"runtime::HOST_ROOTS.len\(\)\s*\+ runtime::LANE_ROOTS.len\(\)"
                r"\s*\+ lane_inv::INV_ROOTS.len\(\)\s*\+ tsfp_lane_c2r::ROOTS.len\(\))"
                r"\s*\);"
            ),
            "assert_eq!(\n"
            "        runtime::ROOTS.len(),\n"
            "        runtime::HOST_ROOTS.len()\n"
            "            + runtime::LANE_ROOTS.len()\n"
            "            + lane_inv::INV_ROOTS.len()\n"
            "            + tsfp_lane_c2r::ROOTS.len()\n"
            "    );",
            output[OUTPUTS[3]],
        )
    # The pinned T2221 migration proof predates the rustfmt step, so it stays raw.
    for name in [] if migration_only else OUTPUTS:
        if name.endswith(".rs"):
            output[name] = rustfmt(root, output[name])
    return output


