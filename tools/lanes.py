EXT_TABLE = re.compile(r"EXT_ROOTS: \[u32; \d+\] = \[([^\]]*)\]")


def ext_lane_overlaps(root: Path) -> tuple[set[int], dict[int, str]]:
    """Addresses registered as both ext root and lane root, and the allowlist (I-T3398-20).

    A declined ext call on a lane root has to fall through to the lane path; an overlap is
    only safe while that fallthrough exists, so each one is listed with a reason. The list
    can only shrink: an entry that no longer overlaps fails the check.
    """
    table = EXT_TABLE.search((root / EXT_SOURCE).read_text())
    if table is None:
        raise ValueError(f"EXT_ROOTS table not found in {EXT_SOURCE}")
    ext = {int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)", table.group(1))}
    manifest = json.loads((root / MANIFEST).read_text())
    lane = {int(r["va"], 16) for lane in manifest["lanes"] for r in lane["roots"]}
    for label in ("LANE_ROOTS", "HOST_ROOTS"):
        lane |= {int(r["va"], 16) for r in manifest["legacy"].get(label, {}).get("roots", [])}
    allow = {}
    for entry in json.loads((root / EXT_ALLOWLIST).read_text())["allowed"]:
        if not entry.get("reason", "").strip():
            raise ValueError(f"ext/lane overlap allowlist entry {entry['va']} has no reason")
        allow[int(entry["va"], 16)] = entry["reason"]
    return ext & lane, allow


def check_ext_lane_overlap(root: Path) -> list[str]:
    overlaps, allow = ext_lane_overlaps(root)
    errors = [
        f"ext root {va:08X} is also a lane root: a declined ext call aborts the lane wrapper "
        f"(I-T3398-20); drop one registration or allowlist it in {EXT_ALLOWLIST} with a reason"
        for va in sorted(overlaps - allow.keys())
    ]
    errors += [
        f"{EXT_ALLOWLIST}: {va:08X} no longer overlaps; remove the entry (the list only shrinks)"
        for va in sorted(allow.keys() - overlaps)
    ]
    return errors


def run(root: Path, *, check: bool, registry: bool = True) -> int:
    output = generate(root)
    stale = [name for name, text in output.items() if (root / name).read_bytes() != text.encode()]
    if check:
        for name in stale:
            print(f"stale lane registration: {name}; run python3 -m tools.lanes regen")
    else:
        for name in stale:
            write_lf_text(root / name, output[name])
    result = int(check and bool(stale))
    if check:
        problems = check_ext_lane_overlap(root)
        for problem in problems:
            print(f"lane registry: {problem}")
        result |= int(bool(problems))
    if registry:
        from tools import portreg

        result |= portreg.main(["--root", str(root), "--check"])
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", nargs="?", choices=["regen"])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=Path.cwd())
    args = parser.parse_args()
    if args.check == bool(args.action):
        parser.error("choose regen or --check")
    try:
        return run(args.root, check=args.check)
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"lane registry: {error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
