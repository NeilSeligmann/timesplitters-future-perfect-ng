"""T1967: build-directory adapters, retained originals and root table for the c2r weapon roots.

The roots are the `WEAPON_ROOTS` of crates/tsfp-ports/src/weapons_lane.rs. For every root that has a
lifted definition and no src/game registration this writes into --out-dir:

* `rust_weapon_adapters.c`: strong `sub_<VA>` calling `GAME_RUST_TRY`, then popping the return
  the callee-cleaned arguments (the cleanup is read from the `ret N` of the lifted body).
* `weakw_<chunk>.h`: `#pragma weak` for the chunk defining the lifted body (force-included).
* `rust_weapon_roots.h`: `TSFP_WPN_ROOTS(X)` with `X(va, pops)`.
* `rust_weapon_originals.c`: the retained lifted originals (`tsfp_original_<va>`).
* `weapon_roots.json`: hooked and unhooked roots with the reason (no lifted body, or in src/game).
Nothing here touches src/game or the registry census (same approach as tools/play/rust_adapters.py).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from tools.play.rust_originals import preserve
from tools.replace.invpose_meta import describe
from tools.replace.scan import registered_in_any_variant
from tools.replace.wiring import DEFINITION

LANE = Path("crates/tsfp-ports/src/weapons_lane.rs")
PICKUP = Path("crates/tsfp-ports/src/pickup_tick.rs")


def weapon_roots(root: Path = Path("."), table: str = "WEAPON_ROOTS") -> list[int]:
    text = (root / LANE).read_text()
    block = text.split(f"pub const {table}", 1)[1].split("];", 1)[0].split("= [", 1)[1]
    return [int(token, 16) for token in re.findall(r"0x[0-9a-f]+", block)]


INV_ROOTS = Path("tools/replace/invpose_roots.json")


def inv_roots(root: Path = Path(".")) -> set[int]:
    """Roots registered on the INV lane (generated from crates/tsfp-ports/lanes.json)."""
    return {int(row["va"], 16) for row in json.loads((root / INV_ROOTS).read_text())["roots"]}


def partition(
    roots: list[int], registered: set[int], inv: set[int], defined: dict[str, str]
) -> tuple[list[int], dict[str, str]]:
    """Hooked roots and the skip reason of the others. A root on the INV lane is owned there: a
    second adapter and selector case would collide (0xE91F0 and 0xE9380 since T2122)."""
    hooked, skipped = [], {}
    for va in roots:
        if va in registered:
            skipped[f"{va:08x}"] = "registered in src/game (its adapter owns the call)"
        elif va in inv:
            skipped[f"{va:08x}"] = "registered on the INV lane (lanes.json owns the call)"
        elif f"sub_{va:08X}" not in defined:
            skipped[f"{va:08x}"] = "no lifted definition"
        else:
            hooked.append(va)
    return hooked, skipped


def pickup_roots(root: Path = Path(".")) -> list[int]:
    """T3398: the pickup tick roots (`ROOTS` in crates/tsfp-ports/src/pickup_tick.rs)."""
    text = (root / PICKUP).read_text()
    block = text.split("pub const ROOTS", 1)[1].split("];", 1)[0].split("= [", 1)[1]
    return [int(token, 16) for token in re.findall(r"0x[0-9a-fA-F_]+", block.replace("_", ""))]


def lane_roots(root: Path = Path(".")) -> list[int]:
    """Every c2r lane root: weapon roots, T2021 player roots, then T2305 settings roots."""
    return (
        weapon_roots(root)
        + weapon_roots(root, "PLAYER_ROOTS")
        + weapon_roots(root, "SETTINGS_ROOTS")
        + pickup_roots(root)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gen-dir", type=Path, required=True)
    parser.add_argument("--game-dir", type=Path, default=Path("src/game"))
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    roots = lane_roots()
    registered = registered_in_any_variant(args.game_dir)
    defined: dict[str, str] = {}
    for chunk in sorted(args.gen_dir.glob("recomp_*.c")):
        for match in DEFINITION.finditer(chunk.read_text(encoding="utf-8", errors="replace")):
            defined[match.group(1)] = chunk.name
    hooked, skipped = partition(roots, registered, inv_roots(), defined)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for stale in args.out_dir.glob("weakw_recomp_*.h"):
        stale.unlink()
    by_chunk: dict[str, list[str]] = {}
    pops: dict[int, int] = {}
    for va in hooked:
        by_chunk.setdefault(defined[f"sub_{va:08X}"], []).append(f"sub_{va:08X}")
        rets = describe(args.gen_dir, va)["ret_pops"]
        pops[va] = min(rets, default=0) // 4  # 1c55f0 also has a junk "ret" in data decoded as code
    for chunk, symbols in by_chunk.items():
        (args.out_dir / f"weakw_{chunk[:-2]}.h").write_text(
            "/* Generated by tools/play/rust_weapons.py (T1967). */\n"
            + "".join(f"#pragma weak {s}\n" for s in sorted(symbols))
        )
    lines = [
        "/* Generated by tools/play/rust_weapons.py (T1967). */",
        '#include "game_replace.h"',
        "#include <stdlib.h>",
        "",
    ]
    for va in hooked:
        lines += [
            f"void sub_{va:08X}(void);",
            f"void sub_{va:08X}(void)",
            "{",
            f"    if (!GAME_RUST_TRY({va:08X})) abort();",
            f"    g_esp += 4u + 4u * {pops[va]}u;",
            "}",
        ]
    (args.out_dir / "rust_weapon_adapters.c").write_text("\n".join(lines) + "\n")
    rows = " \\\n".join(f"    X({va:08x}, {pops[va]})" for va in hooked)
    (args.out_dir / "rust_weapon_roots.h").write_text(
        f"/* Generated by tools/play/rust_weapons.py (T1967). */\n"
        f"#define TSFP_WPN_ROOTS(X) \\\n{rows}\n"
    )
    preserve(args.gen_dir, args.out_dir / "rust_weapon_originals.c", tuple(hooked))
    (args.out_dir / "weapon_roots.json").write_text(
        json.dumps(
            {
                "hooked": [f"{va:08x}" for va in hooked],
                "pops": {f"{k:08x}": v for k, v in pops.items()},
                "skipped": skipped,
            },
            indent=1,
            sort_keys=True,
        )
        + "\n"
    )
    print(f"{len(hooked)} weapon roots hooked, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
