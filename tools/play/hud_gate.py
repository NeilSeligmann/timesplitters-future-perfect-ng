def gates(root: Path = Path(".")) -> list[tuple[int, str]]:
    """(va, element) in table order."""
    rows = json.loads((root / GATES).read_text())["gates"]
    return [(int(row["va"], 16), row["element"]) for row in rows]


def register_gates(root: Path = Path(".")) -> set[int]:
    """Drawers with register arguments and a row cursor advance (`"regs"` in the table)."""
    rows = json.loads((root / GATES).read_text())["gates"]
    return {int(row["va"], 16) for row in rows if row.get("regs") == "eax_record_esi_cursor"}


def xmm_gates(root: Path = Path(".")) -> set[int]:
    """Drawers taking `xmm0` (f32) and a stack row cursor (`"regs": "xmm0_stack_cursor"`)."""
    rows = json.loads((root / GATES).read_text())["gates"]
    return {int(row["va"], 16) for row in rows if row.get("regs") == "xmm0_stack_cursor"}


