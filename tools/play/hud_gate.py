"""T2312: per-element legacy HUD gate, generated into the build directory.

For every drawer of tools/data/hud_native_gates.json that has a lifted definition and no src/game
registration this writes into --out-dir:

* `hud_gate_adapters.c`: strong `sub_<VA>` that asks the Rust shell `tsfp_hud_native_owns(va, esp)`
  (weak, absent means legacy; `esp` points at the return slot, the drawer's arguments follow).
  Owned: the drawer is skipped (return slot and callee-cleaned arguments popped, nothing drawn,
  EAX 0). Not owned: the retained lifted original runs unchanged.
  Register gates (`"regs": "eax_record_esi_cursor"`, the rank box 0x12EC20): the drawer takes `eax`
  (a record) and `esi` (pointer to the HUD column row cursor) and adds the row height to `*esi`.
  The gate asks `tsfp_hud_native_owns_row(va, esp, eax, esi, &advance)`; owned: the native row
  height advances the Rust-owned column (EAX = the height); retained consumers
  query the same native column and the gate performs no guest store.
  `"regs": "xmm0_stack_cursor"` (the effect icons 0x12F670): `xmm0` carries the row alpha
  and `[esp+4]` points at the row cursor. The gate asks
  `tsfp_hud_native_owns_xmm(va, esp, xmm0 bits, &advance)`; owned: the native row height is
  consumed by the native allocator; EAX remains the original cursor pointer ABI.
* `weakh_<chunk>.h`: `#pragma weak` for the chunk that defines the lifted body (force-included).
* `hud_gate_originals.c`: the retained lifted originals (`tsfp_hud_original_<va>`).
* `hud_gates.json`: hooked and skipped drawers with the reason.
Same approach as tools/play/rust_weapons.py: nothing touches src/game or the registry census.
"""

