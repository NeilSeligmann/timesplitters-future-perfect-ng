def attach_weapon_metrics(output: Path) -> None:
    """Retained consumers read the explicit native metric contract when selected.

    This is not a guest-memory overlay: the provider receives a player slot and
    metric enum. Producer/writer reference bodies remain untouched.
    """
    source = output.read_text()
    declarations = (
        "extern int tsfp_hud_weapon_metric(uint32_t, uint32_t, uint32_t *) __attribute__((weak));\n"
        "extern int tsfp_hud_weapon_target(uint32_t, uint32_t) __attribute__((weak));\n"
        "static uint32_t hud_weapon_metric(uint32_t record, uint32_t field) {\n"
        "    uint32_t value;\n"
        "    if (record >= 0x7A6160u && (record - 0x7A6160u) % 0x177Cu == 0u &&\n"
        "        tsfp_hud_weapon_metric &&\n"
        "        tsfp_hud_weapon_metric((record - 0x7A6160u) / 0x177Cu, field, &value))\n"
        "        return value;\n"
        "    return MEM32(record + 0x1750u + field * 4u);\n"
        "}\n"
        "static float hud_weapon_float(uint32_t record, uint32_t field) {\n"
        "    union { uint32_t word; float value; } bits;\n"
        "    bits.word = hud_weapon_metric(record, field); return bits.value;\n"
        "}\n"
        "static void hud_weapon_target(uint32_t record, float value) {\n"
        "    union { uint32_t word; float value; } bits; bits.value = value;\n"
        "    if (record >= 0x7A6160u && (record - 0x7A6160u) % 0x177Cu == 0u &&\n"
        "        tsfp_hud_weapon_target &&\n"
        "        tsfp_hud_weapon_target((record - 0x7A6160u) / 0x177Cu, bits.word)) return;\n"
        "    MEMF(record + 0x1760u) = value;\n"
        "}\n"
    )
    definition = re.compile(r"^void tsfp_hud_original_([0-9a-f]{8})\(void\).*?^\}", re.M | re.S)

    def adapt(match: re.Match[str]) -> str:
        if int(match[1], 16) not in WEAPON_METRIC_CONSUMERS:
            return match[0]
        body = re.sub(
            r"MEMF\((\w+) \+ 0x1760\) = ([^;]+);",
            lambda field: f"hud_weapon_target({field[1]}, {field[2]});",
            match[0],
        )
        body = re.sub(
            r"MEMF\((\w+) \+ 0x(1754|1758|175C|1760|1764)\)",
            lambda field: f"hud_weapon_float({field[1]}, {(int(field[2], 16) - 0x1750) // 4}u)",
            body,
        )
        return re.sub(
            r"MEM32\((\w+) \+ 0x(1750|1754|1758|175C|1760|1764)\)",
            lambda field: f"hud_weapon_metric({field[1]}, {(int(field[2], 16) - 0x1750) // 4}u)",
            body,
        )

    source = source.replace("#include <math.h>\n", "#include <math.h>\n" + declarations)
    source = definition.sub(adapt, source)
    output.write_text(source)
    metadata_path = output.with_suffix(".json")
    metadata = json.loads(metadata_path.read_text())
    metadata["source_sha256"] = hashlib.sha256(source.encode()).hexdigest()
    metadata["native_weapon_metric_consumers"] = [
        f"0x{va:08X}" for va in sorted(WEAPON_METRIC_CONSUMERS)
    ]
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")


def attach_row_metrics(output: Path) -> None:
    """Explicit per-viewer ammo/status contracts for retained HUD consumers."""
    source = output.read_text()
    declarations = (
        "extern int tsfp_hud_row_metric(uint32_t, uint32_t, uint32_t, uint32_t, uint32_t *)"
        " __attribute__((weak));\n"
        "static uint32_t hud_viewer_slot(void) { return MEM32(MEM32(0x7B0C7Cu) + 4u); }\n"
        "static uint32_t hud_ammo_index(uint32_t record, uint32_t side) {\n"
        "    uint32_t out;\n"
        "    if (record >= 0x7A6160u && (record - 0x7A6160u) % 0x177Cu == 0u &&\n"
        "        tsfp_hud_row_metric && tsfp_hud_row_metric((record - 0x7A6160u) / 0x177Cu,\n"
        "        side, 0u, 0u, &out)) return out;\n"
        "    return MEM8(record + 0x174Cu + side);\n"
        "}\n"
        "static void hud_ammo_set(uint32_t record, uint32_t side, uint32_t value) {\n"
        "    uint32_t out;\n"
        "    if (record >= 0x7A6160u && (record - 0x7A6160u) % 0x177Cu == 0u &&\n"
        "        tsfp_hud_row_metric && tsfp_hud_row_metric((record - 0x7A6160u) / 0x177Cu,\n"
        "        side, 1u, value, &out)) return;\n"
        "    MEM8(record + 0x174Cu + side) = (uint8_t)value;\n"
        "}\n"
        "static uint32_t hud_column_top(uint32_t origin) {\n"
        "    uint32_t slot = hud_viewer_slot(), out;\n"
        "    if (tsfp_hud_row_metric && tsfp_hud_row_metric(slot, 2u, 0u, 0u, &out)) return out;\n"
        "    uint32_t initial = MEM32(origin);\n"
        "    if (tsfp_hud_row_metric &&\n"
        "        tsfp_hud_row_metric(slot, 2u, 3u, initial, &out)) return out;\n"
        "    return initial;\n"
        "}\n"
        "static void hud_column_set(uint32_t origin, uint32_t value) {\n"
        "    uint32_t out;\n"
        "    if (tsfp_hud_row_metric &&\n"
        "        tsfp_hud_row_metric(hud_viewer_slot(), 2u, 1u, value, &out)) return;\n"
        "    MEM32(origin) = value;\n"
        "}\n"
    )
    definition = re.compile(r"^void tsfp_hud_original_([0-9a-f]{8})\(void\).*?^\}", re.M | re.S)

    def column(body: str, registers: tuple[str, ...]) -> str:
        for register in registers:
            body = re.sub(
                rf"MEM32\({re.escape(register)}\) = ([^;]+);",
                lambda m, register=register: f"hud_column_set({register}, {m[1]});",
                body,
            )
            body = body.replace(f"MEM32({register})", f"hud_column_top({register})")
        return body

    def adapt(match: re.Match[str]) -> str:
        va = int(match[1], 16)
        body = match[0]
        if va not in ROW_CONSUMERS:
            return body
        if va == 0x1334D0:
            body = re.sub(
                r"MEM8\(ebx \+ (\w+) \+ 0x174C\) = ([^;]+);",
                lambda m: f"hud_ammo_set({m[1]}, ebx, {m[2]});",
                body,
            )
            body = re.sub(
                r"MEM8\(ebx \+ (\w+) \+ 0x174C\)", lambda m: f"hud_ammo_index({m[1]}, ebx)", body
            )
        elif va == ROW_FRAME:
            for offset, side in (("174C", 0), ("174D", 1)):
                body = re.sub(
                    rf"MEM8\(esi \+ 0x{offset}\) = ([^;]+);",
                    lambda m, side=side: f"hud_ammo_set(esi, {side}u, {m[1]});",
                    body,
                )
        elif va == 0x14F0B0:
            body = body.replace(
                "MEM8(ebx + 0x174C) = MEM8(ebx + 0x174C) + 1;",
                "hud_ammo_set(ebx, 0u, hud_ammo_index(ebx, 0u) + 1u);",
            )
            start = body.find("loc_0014F85B:")
            end = body.find("loc_0014F892:", start)
            if start < 0 or end < 0:
                raise ValueError("HUD parent status/effects clamp anchors unavailable")
            body = body[:start] + column(body[start:end], ("esp + 0x10",)) + body[end:]
        elif va == 0x12F670:
            body = column(body, ("ecx", "eax"))
        else:
            body = column(body, ("esi",))
        return body

    source = source.replace("#include <math.h>\n", "#include <math.h>\n" + declarations)
    source = definition.sub(adapt, source)
    output.write_text(source)
    metadata_path = output.with_suffix(".json")
    metadata = json.loads(metadata_path.read_text())
    metadata["source_sha256"] = hashlib.sha256(source.encode()).hexdigest()
    metadata["native_row_consumers"] = [f"0x{va:08X}" for va in sorted(ROW_CONSUMERS)]
    metadata_path.write_text(json.dumps(metadata, indent=2) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gen-dir", type=Path, required=True)
    parser.add_argument("--game-dir", type=Path, default=Path("src/game"))
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    wanted = list(
        dict.fromkeys(
            [va for va, _ in gates()]
            + sorted(
                MESSAGE_ADMISSIONS
                | MESSAGE_NOTICES
                | MESSAGE_CLEARS
                | MESSAGE_KIND6
                | PRODUCERS
                | WEAPON_EVENTS
                | WEAPON_METRIC_CONSUMERS
                | ROW_CONSUMERS
            )
        )
    )
    registered = registered_in_any_variant(args.game_dir)
    # A drawer already owned by another generated adapter (INV lane, c2r weapon lane) keeps it.
    owned = inv_roots() | set(lane_roots())
    defined: dict[str, str] = {}
    for chunk in sorted(args.gen_dir.glob("recomp_*.c")):
        for match in DEFINITION.finditer(chunk.read_text(encoding="utf-8", errors="replace")):
            defined[match.group(1)] = chunk.name
    hooked, skipped = partition(wanted, registered, owned, defined)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for stale in args.out_dir.glob("weakh_recomp_*.h"):
        stale.unlink()
    by_chunk: dict[str, list[str]] = {}
    pops: dict[int, int] = {}
    for va in hooked:
        by_chunk.setdefault(defined[f"sub_{va:08X}"], []).append(f"sub_{va:08X}")
        pops[va] = min(describe(args.gen_dir, va)["ret_pops"], default=0) // 4
    for chunk, symbols in by_chunk.items():
        (args.out_dir / f"weakh_{chunk[:-2]}.h").write_text(
            "/* Generated by tools/play/hud_gate.py (T2312). */\n"
            + "".join(f"#pragma weak {s}\n" for s in sorted(symbols))
        )
    (args.out_dir / "hud_gate_adapters.c").write_text(
        adapter_source(hooked, pops, frozenset(register_gates()), frozenset(xmm_gates()))
    )
    preserve(args.gen_dir, args.out_dir / "hud_gate_originals.c", tuple(hooked), PREFIX)
    attach_weapon_metrics(args.out_dir / "hud_gate_originals.c")
    attach_row_metrics(args.out_dir / "hud_gate_originals.c")
    (args.out_dir / "hud_gates.json").write_text(
        json.dumps(
            {
                "hooked": [f"{va:08x}" for va in hooked],
                "pops": {f"{k:08x}": v for k, v in pops.items()},
                "skipped": skipped,
            },
            indent=1,
            sort_keys=True,
        )
        + "\n"
    )
    print(f"{len(hooked)} HUD drawers gated, {len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
