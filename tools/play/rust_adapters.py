"""T1874: build-directory adapters for the Rust lane roots that have no C replacement in src/game.

A hybrid host (TSFP_RUST_PORTS) routes a call to a root through `game_rust_try`. Roots with a
GAME_REPLACE adapter in src/game already do (the macro calls it). The 99 inventory and
pose/control roots of T1850 have none, and registering them in src/game would make them appear
as replacements to the registry, the census tests and the proof snapshot. So the adapter of
such a root is generated here, into the (ignored) build directory:

* `rust_invpose_adapters.c`: a strong `sub_<VA>` per root that calls `game_rust_try` and then
  pops its return slot and callee-cleaned arguments exactly like GAME_REPLACE_EXACT.
* `weak_<chunk>.h`: `#pragma weak sub_<VA>` for the chunk that defines the lifted body, to be
  force-included into that chunk only (the mechanism of tools/replace/wiring.py).

Roots that src/game registers by itself are skipped, so a later C replacement of the same
address cannot produce a duplicate symbol. Stdlib plus the repository's scan/wiring modules.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from tools.replace.rust_lane import INV_HOST_ROOTS, inv_registration
from tools.replace.scan import registered_in_any_variant
from tools.replace.wiring import DEFINITION, header_name, render_header


def plan(gen_dir: Path, game_dir: Path) -> tuple[list[int], dict[str, list[str]]]:
    registered = registered_in_any_variant(game_dir)
    roots = [va for va in INV_HOST_ROOTS if va not in registered]
    wanted = {f"sub_{va:08X}" for va in roots}
    by_chunk: dict[str, list[str]] = {}
    seen: set[str] = set()
    for chunk in sorted(gen_dir.glob("recomp_*.c")):
        text = chunk.read_text(encoding="utf-8", errors="replace")
        for match in DEFINITION.finditer(text):
            symbol = match.group(1)
            if symbol in wanted:
                by_chunk.setdefault(chunk.name, []).append(symbol)
                seen.add(symbol)
    missing = sorted(wanted - seen)
    if missing:
        raise SystemExit("no lifted definition for " + ", ".join(missing))
    return roots, {chunk: sorted(symbols) for chunk, symbols in by_chunk.items()}


def adapters_text(roots: list[int]) -> str:
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/* Generated by tools/play/rust_adapters.py (T1874). Do not edit. */",
        '#include "game_replace.h"',
        "#include <stdlib.h>",
        "extern int tsfp_hud_weapon_event_abi(uint32_t va) __attribute__((weak));",
        "",
    ]
    for va in roots:
        registration = inv_registration(va)
        pops = registration.stack_args if registration.convention == "stdcall" else 0
        lines += [
            f"void sub_{va:08X}(void);",
            f"void sub_{va:08X}(void)",
            "{",
        ]
        if va in {0x142880, 0x142900}:
            lines += [
                f"    if (tsfp_hud_weapon_event_abi && tsfp_hud_weapon_event_abi(0x{va:08X}u)) {{",
                f"        g_esp += 4u + 4u * {pops}u;",
                "        return;",
                "    }",
            ]
        lines += [
            f"    if (!GAME_RUST_TRY({va:08X})) abort();",
            f"    g_esp += 4u + 4u * {pops}u;",
            "}",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gen-dir", type=Path, required=True)
    parser.add_argument("--game-dir", type=Path, default=Path("src/game"))
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    roots, by_chunk = plan(args.gen_dir, args.game_dir)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for stale in args.out_dir.glob("weak_recomp_*.h"):
        stale.unlink()
    for chunk, symbols in by_chunk.items():
        (args.out_dir / header_name(chunk)).write_text(render_header(chunk, tuple(symbols)))
    (args.out_dir / "rust_invpose_adapters.c").write_text(adapters_text(roots))
    index = {chunk: {"header": header_name(chunk), "symbols": s} for chunk, s in by_chunk.items()}
    (args.out_dir / "adapters.json").write_text(json.dumps(index, indent=1, sort_keys=True) + "\n")
    print(f"{len(roots)} adapters in {len(by_chunk)} chunks")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
