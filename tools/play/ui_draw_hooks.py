"""T2309: build-directory pieces of the per-page legacy draw switch (src/host/ui_draw_hook.c).

The original front end draws a page and its widget tree through 0x76810 (recursive, cdecl
`(widget, pass, depth)`). When the Rust UI draws a page inside the engine frame, the C hook
asks the shell (`tsfp_ui_page_draw_owned`) per widget and skips the original draw of a page the
Rust UI owns, so the page is not drawn twice. For every hooked VA this writes into --out-dir:

* `weaku_<chunk>.h`: `#pragma weak sub_<VA>` for the chunk defining the lifted body
  (force-included), so the strong hook in src/host/ui_draw_hook.c wins for every caller,
  the dispatch table included.
* `ui_draw_originals.c`: the retained lifted original, renamed `tsfp_uihook_original_<va>`.

The hooked VA must not be a src/game replacement or a Rust lane, inventory or weapon root (those
own `sub_<VA>` already); the script refuses then. Same approach as tools/play/rust_weapons.py.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from tools.play.rust_originals import ORIGINALS, preserve
from tools.replace.scan import registered_in_any_variant
from tools.replace.wiring import DEFINITION

# 0x76810 `game_ui_widget_draw_full_pass_frame_background_items_scroll_and_callbacks` (T1465 name).
HOOKS = (0x00076810, 0x00024EC0, 0x00314A50, 0x00081C60)
PREFIX = "tsfp_uihook_original_"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gen-dir", type=Path, required=True)
    parser.add_argument("--game-dir", type=Path, default=Path("src/game"))
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    registered = registered_in_any_variant(args.game_dir)
    clash = [va for va in HOOKS if va in registered or va in ORIGINALS]
    if clash:
        raise SystemExit(
            "ui_draw_hooks: already owned by a replacement or Rust root: "
            + ",".join(f"{va:08X}" for va in clash)
        )
    defined: dict[str, str] = {}
    for chunk in sorted(args.gen_dir.glob("recomp_*.c")):
        for match in DEFINITION.finditer(chunk.read_text(encoding="utf-8", errors="replace")):
            defined[match.group(1)] = chunk.name
    missing = [va for va in HOOKS if f"sub_{va:08X}" not in defined]
    if missing:
        raise SystemExit(
            "ui_draw_hooks: no lifted definition for " + ",".join(f"{va:08X}" for va in missing)
        )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for stale in args.out_dir.glob("weaku_recomp_*.h"):
        stale.unlink()
    by_chunk: dict[str, list[str]] = {}
    for va in HOOKS:
        by_chunk.setdefault(defined[f"sub_{va:08X}"], []).append(f"sub_{va:08X}")
    for chunk, symbols in by_chunk.items():
        (args.out_dir / f"weaku_{chunk[:-2]}.h").write_text(
            "/* Generated by tools/play/ui_draw_hooks.py (T2309). */\n"
            + "".join(f"#pragma weak {s}\n" for s in sorted(symbols))
        )
    preserve(args.gen_dir, args.out_dir / "ui_draw_originals.c", HOOKS, prefix=PREFIX)
    (args.out_dir / "ui_draw_hooks.json").write_text(
        json.dumps({"hooked": [f"{va:08x}" for va in HOOKS], "chunks": by_chunk}, indent=1) + "\n"
    )
    print(f"{len(HOOKS)} hooked in {len(by_chunk)} chunk(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
