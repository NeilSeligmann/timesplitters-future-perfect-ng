"""System dispositions (AGENTS.md owner rule 14): port, replace, spec, drop, undecided.

Table: tools/data/system_dispositions.json, longest-prefix match on the ledger subsystem name.
`library` is a fifth class that the breadth bar ignores (as before rule 14)."""

from __future__ import annotations

import csv
import json
import subprocess
from collections.abc import Iterable, Mapping
from pathlib import Path

DEFAULT_PATH = Path("tools/data/system_dispositions.json")
CLASSES = ("port", "replace", "spec", "drop", "undecided", "library")
SKIP = "drop"
LAST = "replace"


def load(path: Path | None = None) -> dict[str, str]:
    """subsystem prefix -> class. Empty when the table is missing (everything undecided)."""
    path = path or DEFAULT_PATH
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {name: str(entry["d"]) for name, entry in data["systems"].items()}


def load_full(path: Path | None = None) -> dict[str, object]:
    return json.loads((path or DEFAULT_PATH).read_text(encoding="utf-8"))


def disposition_of(subsystem: str, table: Mapping[str, str]) -> str:
    parts = (subsystem or "unknown").split("/")
    for size in range(len(parts), 0, -1):
        found = table.get("/".join(parts[:size]))
        if found:
            return found
    return "library" if parts[0] == "library" else "undecided"


def of_rows(rows: Iterable[Mapping[str, object]], table: Mapping[str, str]) -> dict[int, str]:
    return {int(str(r["va"]), 16): disposition_of(str(r["subsystem"]), table) for r in rows}


GENERATED_END = "<!-- generated-end -->"
CONTRACT_TBD = "contract TBD"


def render_doc(rows: list[Mapping[str, object]], weights: object, table: Mapping[str, str]) -> str:
    """Markdown body of docs/t-system-dispositions.md (everything above GENERATED_END)."""
    from tools.ledger import execution

    full = load_full()
    contracts: Mapping[str, str] = full.get("contracts", {})  # type: ignore[assignment]
    why = {k: v["why"] for k, v in full["systems"].items()}  # type: ignore[index,union-attr]
    disp = of_rows(rows, table)
    bar = execution.disposition_table(rows, weights, disp)  # type: ignore[arg-type]
    per: dict[str, dict[str, int]] = {}
    for row in rows:
        va = int(str(row["va"]), 16)
        name = str(row["subsystem"])
        b = per.setdefault(name, {"fn": 0, "ported": 0, "calls": 0})
        b["fn"] += 1
        port = (row.get("obligations") or {}).get("rust_port") or {}  # type: ignore[union-attr]
        b["ported"] += 1 if port.get("status") == "done" else 0
        if weights is not None:
            b["calls"] += weights.calls.get(va, 0)  # type: ignore[attr-defined]
    lines = [
        "# System dispositions (owner rule 14, T2011)",
        "",
        "Generated by `python3 -m tools.ledger dispositions --write` from "
        "`tools/data/system_dispositions.json` and the obligation ledger. Decision: "
        "[system-dispositions](decisions/system-dispositions.md). Confidence: MEASURED "
        "(ledger plus execution weights `docs/data/t1884-exec-weights.csv`).",
        "",
        "## Totals per disposition (game functions in the ledger; library excluded)",
        "",
        "| disposition | functions | ported | Tier>=1 | executed calls | share of calls |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name in CLASSES:
        r = bar[name]
        lines.append(
            f"| {name} | {r['functions']} | {r['ported']} | {r['tier1']} | {r['calls']} "
            f"| {r['call_share']:.1%} |"
        )
    lines += [
        "",
        "## Per system",
        "",
        "| system | disposition | functions | ported | executed calls | reason |",
        "| --- | --- | ---: | ---: | ---: | --- |",
    ]
    for name in sorted(per, key=lambda n: (disp_name(n, table), n)):
        b = per[name]
        reason = why.get(name) or why.get(name.split("/")[0], "")
        lines.append(
            f"| {name} | {disposition_of(name, table)} | {b['fn']} | {b['ported']} | {b['calls']} "
            f"| {reason} |"
        )
    lines += ["", "## Contract boundaries of the replace systems", ""]
    lines += [
        f"- `{k}`: {contracts.get(k, CONTRACT_TBD)}"
        for k, d in sorted(table.items())
        if d == "replace"
    ]
    lines += [
        "- Existing ports in these systems stay as contract oracles and are not extended.",
        "- `ui/*` (port) draws through `Draw` in `crates/tsfp-ui`.",
        "",
        "## Undecided (excluded from the port bar)",
        "",
        "- `unknown`: " + f"{bar['undecided']['functions']} functions, "
        f"{bar['undecided']['calls']} executed calls until T1893 classifies them.",
        "",
        GENERATED_END,
    ]
    return "\n".join(lines) + "\n"


def disp_name(name: str, table: Mapping[str, str]) -> str:
    return disposition_of(name, table)


# T3744 (I-T3744-6): the one definition of "port-class function" for Tier 2 credit. The ledger
# counts whole-game evidence only for these VAs (`tier2_functions` of verification.load_records)
# and t2capture_promote skips exactly the whole-game credits the ledger counts.
SUBSYSTEMS_PATH = Path("tools/data/function_subsystems.csv")


def port_vas(subsystems: Mapping[int, str], table: Mapping[str, str]) -> set[int]:
    """VAs whose subsystem has the `port` disposition."""
    return {va for va, system in subsystems.items() if disposition_of(system, table) == "port"}


def load_subsystems(path: Path) -> dict[int, str]:
    """va -> subsystem of the placement table (`address`, `subsystem` columns)."""
    with path.open(encoding="utf-8", newline="") as handle:
        return {int(row["address"], 16): row["subsystem"] for row in csv.DictReader(handle)}


def subsystems_path(root: Path) -> Path | None:
    """The gitignored placement table of `root`, else of its main checkout, else None."""
    local = root / SUBSYSTEMS_PATH
    if local.is_file():
        return local
    common = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--path-format=absolute", "--git-common-dir"],
        capture_output=True, text=True, check=False, timeout=60,
    ).stdout.strip()  # fmt: skip
    main = Path(common).parent / SUBSYSTEMS_PATH if common else None
    return main if main is not None and main.is_file() else None


def tier2_port_vas(root: Path) -> set[int] | None:
    """Port-class VAs of the tree at `root` (dispositions + placement), None when unplaced."""
    path = subsystems_path(root)
    if path is None:
        return None
    return port_vas(load_subsystems(path), load(root / DEFAULT_PATH))
