"""T1874: generate the `TSFP_INV_ROOTS(X)` table (`X(va, pops)`) of src/host/rust_lane_roots.h for the
inventory and pose/control lane roots, in the order of `rust_lane.INV_HOST_ROOTS` and `lane_inv.rs`.
The adapters of the roots without a C replacement are generated into the build directory by
tools/play/rust_adapters.py (no src/game registration, see docs/t1874-rust-admission.md).
"""

from __future__ import annotations

import argparse
from pathlib import Path

from tools.replace.rust_lane import INV_HOST_ROOTS, inv_registration

HEADER = Path("src/host/rust_lane_roots.h")
BEGIN = "/* ---- TSFP_INV_ROOTS begin (generated by tools/replace/gen_invpose_host.py) ---- */\n"
END = "/* ---- TSFP_INV_ROOTS end ---- */\n"


def pops_of(va: int) -> int:
    registration = inv_registration(va)
    return registration.stack_args if registration.convention == "stdcall" else 0


def header_block() -> str:
    rows = " \\\n".join(f"    X({va:08x}, {pops_of(va)})" for va in INV_HOST_ROOTS)
    return f"{BEGIN}#define TSFP_INV_ROOTS(X) \\\n{rows}\n{END}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the files are stale")
    args = parser.parse_args()
    # Compatibility entry point; the manifest now owns every registration output.
    from tools.lanes import run

    return run(Path.cwd(), check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
