/// Page size in pixels.
pub fn page_size() -> (u32, u32) {
    (COLUMNS * CELL_W, COUNT.div_ceil(COLUMNS) * CELL_H)
}

/// Coverage page (one byte per pixel, 255 inside a glyph), cells of 6 x 8 with a 1 px gap.
pub fn coverage() -> Vec<u8> {
    let (width, height) = page_size();
    let mut out = vec![0u8; (width * height) as usize];
    for (index, rows) in ROWS.iter().enumerate() {
        let (cx, cy) = cell(index as u32);
        for (y, bits) in rows.iter().enumerate() {
            for x in 0..5u32 {
                if bits & (0x10 >> x) != 0 {
                    out[((cy + y as u32) * width + cx + x) as usize] = 255;
                }
            }
        }
    }
    out
}

fn cell(index: u32) -> (u32, u32) {
    ((index % COLUMNS) * CELL_W, (index / COLUMNS) * CELL_H)
}

/// Atlas entry for `key`: the 5 x 7 cell scaled so the glyph is 70% of the raster height
/// (cap height, INFERRED proportion), sitting on the baseline; advance from the cell width.
/// None for codes the face does not cover.
pub fn glyph(key: GlyphKey) -> Option<AtlasGlyph> {
    let code = u8::try_from(key.glyph.0).ok()?;
    let index = u32::from(code.checked_sub(FIRST)?);
    if index >= COUNT {
        return None;
    }
    let (width, height) = page_size();
    let (cx, cy) = cell(index);
    let pixel = (key.raster_height_px.max(1) as f32 * 0.7 / 7.0).max(1.0);
    Some(AtlasGlyph {
        texture: PAGE,
        uv: UvRect {
            min: Vec2::new(cx as f32 / width as f32, cy as f32 / height as f32),
            max: Vec2::new(
                (cx + 5) as f32 / width as f32,
                (cy + 7) as f32 / height as f32,
            ),
        },
        size_px: Vec2::new(5.0 * pixel, 7.0 * pixel),
        bearing_px: Vec2::new(0.0, 7.0 * pixel),
        advance_px: 6.0 * pixel,
    })
}

/// Uploads the page (idempotent) and registers every covered key of `keys`. Uncovered codes
/// are returned so the caller can report them; they are dropped from the runs by the caller.
pub fn register(
    renderer: &mut WgpuUiRenderer<'_>,
    keys: &[GlyphKey],
) -> Result<Vec<GlyphKey>, Error> {
    if !renderer.has_texture(PAGE) {
        let (width, height) = page_size();
        renderer.upload_coverage(PAGE, width, height, &coverage())?;
    }
    let mut entries = Vec::new();
    let mut missing = Vec::new();
    for &key in keys {
        match glyph(key) {
            Some(glyph) => entries.push((key, glyph)),
            None => missing.push(key),
        }
    }
    renderer.register_glyphs(&entries)?;
    Ok(missing)
}

#[cfg(test)]
mod tests {
    //! Tier 0, FABRICATED face.
    use super::*;
    use tsfp_ui_renderer::{FontId, GlyphId};

    fn key(code: u32, height: u32) -> GlyphKey {
        GlyphKey {
            font: FontId(4),
            glyph: GlyphId(code),
            raster_height_px: height,
        }
    }

    #[test]
    fn printable_codes_have_cells_and_others_do_not() {
        assert!(glyph(key(0x1F, 20)).is_none());
        assert!(glyph(key(0x7F, 20)).is_none());
        assert!(glyph(key(0x1E9, 20)).is_none());
        let a = glyph(key(u32::from(b'A'), 20)).unwrap();
        let z = glyph(key(u32::from(b'~'), 20)).unwrap();
        assert!(a.uv.min.x < a.uv.max.x && z.uv.max.y <= 1.0);
        assert_eq!(
            a.size_px,
            Vec2::new(10.0, 14.0),
            "20 px raster -> 2 px per dot"
        );
        assert_eq!(a.bearing_px.y, a.size_px.y, "sits on the baseline");
    }

    #[test]
    fn coverage_places_each_glyph_in_its_own_cell() {
        let page = coverage();
        let (width, height) = page_size();
        assert_eq!(page.len(), (width * height) as usize);
        let lit = |index: u32| {
            let (cx, cy) = cell(index);
            (0..CELL_H)
                .flat_map(|y| (0..CELL_W).map(move |x| (x, y)))
                .filter(|&(x, y)| page[((cy + y) * width + cx + x) as usize] != 0)
                .count()
        };
        assert_eq!(lit(0), 0, "space is empty");
        // 'I': rows 0x0E, 0x04 x5, 0x0E = 3 + 5 + 3 dots.
        assert_eq!(lit(u32::from(b'I' - FIRST)), 11);
        // The gap column and row of every cell stay empty.
        for index in 0..COUNT {
            let (cx, cy) = cell(index);
            assert!((0..CELL_H).all(|y| page[((cy + y) * width + cx + 5) as usize] == 0));
            assert!((0..CELL_W).all(|x| page[((cy + 7) * width + cx + x) as usize] == 0));
        }
    }
}
