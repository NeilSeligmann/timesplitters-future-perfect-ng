/* Most lane adapters own all cleanup. The live 0x29e40 Rust lane retains one
 * argument pop in its returned ESP and its generated adapter pops only the
 * return address. Preserve that same boundary when executing the RET 4 lifted
 * body, instead of checking it against the adapter's pop-0 metadata. */
static uint32_t lane_lifted_boundary(uint32_t va, uint32_t entry_esp, int pops, const char *message)
{
    const uint32_t extra = va == 0x00029e40u ? 4u : 0u;
    const uint32_t outer_cleanup = 4u + 4u * (uint32_t)pops;
    if (g_esp != entry_esp + outer_cleanup + extra)
        tsfp_bridge_fail(HOST_STOP_BRIDGE_CONTRACT, va, entry_esp, g_esp, message);
    return g_esp - outer_cleanup;
}
