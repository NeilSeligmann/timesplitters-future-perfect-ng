/* T2346: call-argument detector for tools.rust_trace (--call-args). The entry row records the first four
 * stack arguments, 64-byte digests of plausible pointer arguments, and digests of the input globals most
 * relevant to the selected engine/input roots. The exit row also records EAX and x87 ST0. This catches
 * immediate writes to shared input state even when a later call overwrites them before a frame dump. */
extern __thread double g_fp_stack[8];
extern __thread int g_fp_top;
enum { CALL_ARGS_MAX = 1024 }; /* T3391: was 256, the probe union grew to 403 roots */
typedef struct { uint32_t address, size; } call_args_region;
static const call_args_region call_args_regions[] = {
    {0x6B93C0u, 0x200u}, {0x75AEC8u, 0x34u}, {0x6B9888u, 4u}, {0x76B0FCu, 4u},
    {0x4CA9ACu, 4u}, {0x74CF70u, 0x194u}, {0x7E7240u, 4u}, {0x74F9E4u, 4u},
};
static FILE *call_args_file;
static uint32_t call_args_vas[CALL_ARGS_MAX];
static unsigned call_args_count;
static int call_args_on = -1;
static int call_args_compare(const void *left, const void *right)
{
    const uint32_t a = *(const uint32_t *)left, b = *(const uint32_t *)right;
    return (a > b) - (a < b);
}
static bool call_args_wants(uint32_t va)
{
    if (call_args_on < 0) {
        const char *path = getenv("TSFP_CALL_ARGS_TRACE"), *list = getenv("TSFP_CALL_ARGS_VAS");
        call_args_on = 0;
        if (path != NULL && list != NULL && (call_args_file = fopen(path, "w")) != NULL) {
            setvbuf(call_args_file, NULL, _IOLBF, 0); /* survive a killed host */
            for (char *end = NULL; *list != '\0' && call_args_count < CALL_ARGS_MAX; list = *end ? end + 1 : end) {
                call_args_vas[call_args_count++] = (uint32_t)strtoul(list, &end, 16);
                if (end == list) break;
            }
            qsort(call_args_vas, call_args_count, sizeof call_args_vas[0], call_args_compare);
            call_args_on = call_args_count > 0;
        }
    }
    if (!call_args_on) return false;
    unsigned low = 0, high = call_args_count;
    while (low < high) {
        unsigned middle = low + (high - low) / 2;
        if (call_args_vas[middle] == va) return true;
        if (call_args_vas[middle] < va) low = middle + 1;
        else high = middle;
    }
    return false;
}
static uint32_t call_args_digest(uint32_t pointer, size_t length)
{
    unsigned char bytes[0x200];
    if (length > sizeof bytes || pointer < 0x10000u || pointer >= 0xF0000000u ||
        !native_animation_read(pointer, bytes, length)) return 0u;
    uint32_t hash = 2166136261u;
    for (size_t index = 0; index < length; index++) hash = (hash ^ bytes[index]) * 16777619u;
    return hash;
}
static uint32_t call_args_st0(void)
{
    const float value = (float)g_fp_stack[(unsigned)g_fp_top & 7u];
    uint32_t bits;
    memcpy(&bits, &value, sizeof bits);
    return bits;
}
/* T3702: the calling thread's stack range, so tools.rust_trace_call_args can tell a pointer argument that
 * targets DEAD stack (below the call-time ESP, stale residue) from heap or a live frame. Main guest stack from
 * main.c, other threads from the kernel thread table; unknown stays 0 0 and is never treated as residue. */
extern bool host_main_guest_stack(uint32_t *low, uint32_t *high) __attribute__((weak));
extern unsigned kernel_thread_snapshot(kernel_thread_record *out, unsigned max) __attribute__((weak));
static __thread uint32_t call_args_stack_low, call_args_stack_high;
static void call_args_stack_range(uint32_t esp, uint32_t *low, uint32_t *high)
{
    *low = *high = 0u;
    if (esp == 0u) return;
    if (!(esp >= call_args_stack_low && esp < call_args_stack_high)) {
        call_args_stack_low = call_args_stack_high = 0u;
        uint32_t main_low = 0u, main_high = 0u;
        if (host_main_guest_stack != NULL && host_main_guest_stack(&main_low, &main_high) && esp >= main_low && esp < main_high) {
            call_args_stack_low = main_low, call_args_stack_high = main_high;
        } else if (kernel_thread_snapshot != NULL) {
            kernel_thread_record threads[64];
            const unsigned count = kernel_thread_snapshot(threads, 64u);
            for (unsigned index = 0; index < count && index < 64u; index++)
                if (esp >= threads[index].stack_low && esp < threads[index].stack_high) {
                    call_args_stack_low = threads[index].stack_low, call_args_stack_high = threads[index].stack_high;
                    break;
                }
        }
    }
    if (esp >= call_args_stack_low && esp < call_args_stack_high) *low = call_args_stack_low, *high = call_args_stack_high;
}
static void call_args_row(uint32_t va, unsigned phase, uint32_t first, uint32_t st0, const uint32_t args_in[4], uint32_t esp)
{
    /* T3879: the frame roots take no arguments; the words above the return slot are stack residue that differs between the
     * lifted and the Rust-hosted outer loop (different frames), so neither side records them. */
    static const uint32_t no_args[4] = {0u, 0u, 0u, 0u};
    const uint32_t *args = va == 0x0003C440u || va == 0x001538C0u ? no_args : args_in;
    const unsigned long long poll = (unsigned long long)tsfp_input_host_poll_count(0u);
    uint32_t low = 0u, high = 0u;
    if (esp != 0u) call_args_stack_range(esp, &low, &high);
    flockfile(call_args_file); /* T3388: one row per lock; guest threads tore rows (5 of 28.6 M) */
    fprintf(call_args_file, "%llu %x %u", poll, va, phase);
    if (phase == 0u) fprintf(call_args_file, " %x %x %x %x", args[0], args[1], args[2], args[3]);
    else if (va == 0x0003C440u || va == 0x001538C0u) /* T3879: void frame roots; the leftover EAX is not a return value (0x2d vs 0x26 off/off) */
        fprintf(call_args_file, " 0 0");
    else fprintf(call_args_file, " %x %x", first, st0);
    for (int index = 0; index < 4; index++) fprintf(call_args_file, " %x", call_args_digest(args[index], 64u));
    for (size_t index = 0; index < sizeof call_args_regions / sizeof call_args_regions[0]; index++)
        fprintf(call_args_file, " %x", call_args_digest(call_args_regions[index].address, call_args_regions[index].size));
    if (esp != 0u) { /* T3702: `esp stack_low stack_high`; rows from nested calls (esp 0) keep the classic shape */
        fprintf(call_args_file, " %x %x %x", esp, low, high);
        bool partial_valid[4] = { false, false, false, false };
        uint32_t partial_hash[4] = { 0u, 0u, 0u, 0u };
        unsigned partial_count = 0u;
        for (unsigned index = 0; index < 4u; index++) {
            const uint64_t end = (uint64_t)args[index] + 64u;
            if (low <= args[index] && args[index] < esp && esp < end && end <= high) {
                partial_hash[index] = call_args_digest(esp, (size_t)(end - esp));
                partial_valid[index] = partial_hash[index] != 0u;
                if (partial_valid[index]) partial_count++;
            }
        }
        if (partial_count != 0u) {
            fprintf(call_args_file, " %x", partial_count);
            for (unsigned index = 0; index < 4u; index++) {
                if (partial_valid[index])
                    fprintf(call_args_file, " %x %x", index, partial_hash[index]);
            }
        }
    }
    fputc('\n', call_args_file);
    funlockfile(call_args_file);
}
/* T3421: nested REA handle resolution runs through LaneGuest::call rather than
 * the host root dispatcher. Keep its opt-in trace on the same address-filtered
 * call-args stream so lifted and Rust inputs and EAX can be compared. */
void host_rust_ports_nested_call_args(uint32_t va, unsigned phase, uint32_t arg0, uint32_t eax)
{
    if (!call_args_wants(va)) return;
    const uint32_t args[4] = {arg0, 0u, 0u, 0u};
    call_args_row(va, phase, eax, 0u, args, 0u);
}
/* T3879: the lifted side of a root that has a Rust owner (0x3C440, 0x1538C0 with the frame loop off) is entered by a
 * direct wrapper, not the root dispatcher, so the baseline call-args stream had no rows to compare the Rust rows
 * against. The wrapper records the same entry row the dispatcher writes for the Rust side (the Rust roots have no exit row). */
uint32_t host_rust_ports_lifted_root_enter(uint32_t va)
{
    uint32_t args[4] = {0};
    const uint32_t esp = g_esp;
    if (!call_args_wants(va) || esp > UINT32_MAX - 20u || !native_animation_read(esp + 4u, (unsigned char *)args, sizeof args)) return 0u;
    call_args_row(va, 0u, 0u, 0u, args, esp);
    return esp;
}
/* T3621 capdiff: "capture once, differential many". TSFP_CAPDIFF_SPEC names a text file with one line per
 * root, `va addr+len [addr+len ...]` (hex), TSFP_CAPDIFF_TRACE the output. At every entry of a listed root one
 * row records the register file, eight stack words and the listed guest regions (the memory the function
 * reads). Read-only: no guest register or RAM is changed, so the route and its Tier 2 trace are unaffected.
 * tools.capdiff ingests the rows into a content-addressed corpus; docs/decisions/capture-differential.md. */
enum { CAPDIFF_ROOTS_MAX = 256, CAPDIFF_REGIONS_MAX = 8, CAPDIFF_REGION_BYTES = 0x1000, CAPDIFF_SITES_MAX = 4096 };
typedef struct {
    uint32_t address, offset, length, pointer_offset[2], argument;
    uint32_t index_offset, table_cell, row_stride, row_count;
    unsigned pointer_count;
    unsigned char base_kind, base_index, nullable;
    int indirect, argument_base;
} capdiff_region;
typedef struct { uint32_t va, count; capdiff_region regions[CAPDIFF_REGIONS_MAX]; unsigned long long seen, kept; } capdiff_root;
typedef struct { uint32_t va, pc; unsigned kept; int used; } capdiff_site;
static FILE *capdiff_file;
static capdiff_root capdiff_roots[CAPDIFF_ROOTS_MAX];
static capdiff_site capdiff_sites[CAPDIFF_SITES_MAX];
static unsigned capdiff_root_count;
static unsigned long long capdiff_ordinal, capdiff_limit = 200000ull, capdiff_head = 50000ull, capdiff_stride = 4ull;
static unsigned capdiff_site_quota;
static int capdiff_on = -1;
static const capdiff_root *capdiff_find(uint32_t va)
{
    if (capdiff_on < 0) {
        const char *path = getenv("TSFP_CAPDIFF_TRACE"), *spec = getenv("TSFP_CAPDIFF_SPEC"),
                   *inline_spec = getenv("TSFP_RUST_SHADOW_SPEC"), *cap = getenv("TSFP_CAPDIFF_MAX");
        FILE *list = spec != NULL ? fopen(spec, "r") : NULL;
        capdiff_on = 0;
        /* Per root: keep the first HEAD calls, then every STRIDE-th, at most MAX rows (whole-route coverage, bounded size). */
        if (cap != NULL) capdiff_limit = strtoull(cap, NULL, 10);
        if (getenv("TSFP_CAPDIFF_HEAD") != NULL) capdiff_head = strtoull(getenv("TSFP_CAPDIFF_HEAD"), NULL, 10);
        if (getenv("TSFP_CAPDIFF_STRIDE") != NULL) capdiff_stride = strtoull(getenv("TSFP_CAPDIFF_STRIDE"), NULL, 10) ? strtoull(getenv("TSFP_CAPDIFF_STRIDE"), NULL, 10) : 1ull;
        if (getenv("TSFP_CAPDIFF_SITE_QUOTA") != NULL) capdiff_site_quota = (unsigned)strtoul(getenv("TSFP_CAPDIFF_SITE_QUOTA"), NULL, 10);
        if (path != NULL && list != NULL && (capdiff_file = fopen(path, "w")) != NULL) {
            char line[512];
            char *inline_copy = inline_spec != NULL ? strdup(inline_spec) : NULL;
            char *inline_cursor = NULL;
            char *inline_line = inline_copy != NULL ? strtok_r(inline_copy, ";", &inline_cursor) : NULL;
            while (capdiff_root_count < CAPDIFF_ROOTS_MAX &&
                   (list != NULL ? fgets(line, sizeof line, list) != NULL : inline_line != NULL)) {
                if (list == NULL) {
                    snprintf(line, sizeof line, "%s", inline_line);
                    inline_line = strtok_r(NULL, ";", &inline_cursor);
                }
                char *at = line, *end = NULL;
                capdiff_root *root = &capdiff_roots[capdiff_root_count];
                root->va = (uint32_t)strtoul(at, &end, 16);
                if (end == at) continue;
                for (at = end; root->count < CAPDIFF_REGIONS_MAX; at = end + 1) {
                    capdiff_region *region = &root->regions[root->count];
                    if (*at == '@') {
                        at++;
                        if (strncmp(at, "row(", 4) == 0) {
                            char index_base[8] = {0};
                            int consumed = 0;
                            if (sscanf(at + 4, "%7[^,],%x,%x,%x,%x)%n", index_base,
                                       &region->index_offset, &region->table_cell,
                                       &region->row_stride, &region->row_count, &consumed) != 5 ||
                                strcmp(index_base, "eax") != 0 || consumed <= 0 ||
                                region->row_stride == 0u || region->row_count == 0u) break;
                            region->base_kind = 3u;
                            at += 4 + consumed;
                        } else if (strncmp(at, "eax", 3) == 0) {
                            region->base_kind = 1u;
                            region->argument_base = 1;
                            region->argument = 0u;
                            at += 3;
                        } else if (strncmp(at, "stack", 5) == 0) {
                            char *index_end = NULL;
                            const unsigned long index = strtoul(at + 5, &index_end, 10);
                            if (index_end == at + 5 || index >= 8u) break;
                            region->base_kind = 2u;
                            region->base_index = (unsigned char)index;
                            at = index_end;
                            if (*at == '?') { region->nullable = 1u; at++; }
                        } else break;
                        if (*at != '+') break;
                        region->length = (uint32_t)strtoul(at + 1, &end, 16);
                    } else if (*at == 'r') {
                        region->argument_base = 1;
                        region->indirect = 1;
                        region->argument = (uint32_t)strtoul(at + 1, &end, 16);
                        region->base_kind = 1u;
                        if (end == at + 1 || *end != '+') break;
                        unsigned hops = (unsigned)strtoul(end + 1, &end, 16);
                        if (*end != '+' || hops > 2) break;
                        for (unsigned hop = 0; hop < hops; hop++) {
                            region->pointer_offset[region->pointer_count++] = (uint32_t)strtoul(end + 1, &end, 16);
                            if (hop + 1 < hops && *end != '+') break;
                        }
                        if (*end != '+') break;
                        region->offset = (uint32_t)strtoul(end + 1, &end, 16);
                        if (*end != '+') break;
                        region->length = (uint32_t)strtoul(end + 1, &end, 16);
                    } else if (*at == 'a') {
                        region->argument_base = 1;
                        region->argument = (uint32_t)strtoul(at + 1, &end, 16);
                        region->base_kind = 1u;
                        if (end == at + 1 || *end != '+') break;
                        region->offset = (uint32_t)strtoul(end + 1, &end, 16);
                        if (*end != '+') break;
                        region->length = (uint32_t)strtoul(end + 1, &end, 16);
                    } else if (*at == 'p') {
                        region->indirect = 1;
                        region->address = (uint32_t)strtoul(at + 1, &end, 16);
                        if (end == at + 1 || *end != '+') break;
                        region->offset = (uint32_t)strtoul(end + 1, &end, 16);
                        if (*end != '+') break;
                        region->length = (uint32_t)strtoul(end + 1, &end, 16);
                    } else {
                        region->address = (uint32_t)strtoul(at, &end, 16);
                        if (end == at || *end != '+') break;
                        region->length = (uint32_t)strtoul(end + 1, &end, 16);
                    }
                    root->count++;
                }
                capdiff_root_count++;
            }
            if (capdiff_file != NULL) setvbuf(capdiff_file, NULL, _IOLBF, 0);
            capdiff_on = capdiff_root_count > 0 && (path == NULL || capdiff_file != NULL);
            free(inline_copy);
        }
        if (list != NULL) fclose(list);
    }
    if (!capdiff_on) return NULL;
    for (unsigned index = 0; index < capdiff_root_count; index++)
        if (capdiff_roots[index].va == va) return &capdiff_roots[index];
    return NULL;
}
static void capdiff_row(const capdiff_root *root)
{
    if (capdiff_file == NULL) return;
    unsigned char bytes[CAPDIFF_REGION_BYTES];
    uint32_t stack[8] = {0};
    const unsigned long long poll = (unsigned long long)tsfp_input_host_poll_count(0u);
    capdiff_root *mutable_root = (capdiff_root *)root;
    if (g_esp > UINT32_MAX - sizeof stack || !native_animation_read(g_esp, (unsigned char *)stack, sizeof stack)) return;
    flockfile(capdiff_file);
    const unsigned long long seen = __atomic_fetch_add(&mutable_root->seen, 1ull, __ATOMIC_RELAXED);
    if (capdiff_site_quota != 0) {
        const uint32_t pc = stack[0];
        unsigned slot = (unsigned)((root->va * 2654435761u ^ pc) % CAPDIFF_SITES_MAX);
        unsigned probe;
        for (probe = 0; probe < CAPDIFF_SITES_MAX; probe++, slot = (slot + 1) % CAPDIFF_SITES_MAX) {
            capdiff_site *site = &capdiff_sites[slot];
            if (!site->used) { site->used = 1; site->va = root->va; site->pc = pc; }
            if (site->va == root->va && site->pc == pc) {
                if (site->kept >= capdiff_site_quota) { funlockfile(capdiff_file); return; }
                site->kept++;
                break;
            }
        }
        if (probe == CAPDIFF_SITES_MAX) { funlockfile(capdiff_file); return; }
    } else if (seen >= capdiff_head && (seen - capdiff_head) % capdiff_stride != 0) {
        funlockfile(capdiff_file); return;
    }
    if (__atomic_fetch_add(&mutable_root->kept, 1ull, __ATOMIC_RELAXED) >= capdiff_limit) { funlockfile(capdiff_file); return; }
    const unsigned long long ordinal = __atomic_fetch_add(&capdiff_ordinal, 1ull, __ATOMIC_RELAXED);
    fprintf(capdiff_file, "C %llu %llu %x %x %x %x %x %x %x %x %x S", poll, ordinal, root->va, g_eax, g_ecx, g_edx, g_ebx, g_esi, g_edi, g_ebp, g_esp);
    for (int index = 0; index < 8; index++) fprintf(capdiff_file, " %x", stack[index]);
    fputs(" M", capdiff_file);
    for (uint32_t index = 0; index < root->count; index++) {
        const capdiff_region *region = &root->regions[index];
        uint32_t address = region->address, length = region->length;
        int null_target = 0;
        if (region->base_kind != 0u) {
            uint32_t base = region->base_kind == 1u ? g_eax :
                            region->base_kind == 2u ? stack[region->base_index] : 0u;
            int resolved = 1;
            if (region->base_kind == 3u) {
                uint32_t table = 0u, record = 0u;
                if (g_eax > UINT32_MAX - region->index_offset ||
                    !native_animation_read(g_eax + region->index_offset, (unsigned char *)&record, sizeof record) ||
                    record >= region->row_count ||
                    !native_animation_read(region->table_cell, (unsigned char *)&table, sizeof table) ||
                    table == 0u || record > (UINT32_MAX - table) / region->row_stride) {
                    resolved = 0;
                    base = 0u;
                } else base = table + record * region->row_stride;
            }
            if (base == 0u && region->nullable && resolved) {
                fprintf(capdiff_file, " 0:");
            } else if (resolved && base != 0u && length <= sizeof bytes &&
                       base <= UINT32_MAX - length && native_animation_read(base, bytes, length)) {
                fprintf(capdiff_file, " %x:", base);
                for (uint32_t byte = 0; byte < length; byte++) fprintf(capdiff_file, "%02x", bytes[byte]);
            } else {
                fprintf(capdiff_file, " %x:-", base);
            }
            continue;
        }
        if (region->argument_base) {
            if (region->argument >= 4) { fputs(" 0:-", capdiff_file); continue; }
            address = stack[region->argument + 1];
            if (address == 0) null_target = 1;
            if (region->indirect) {
                for (unsigned hop = 0; hop < region->pointer_count; hop++) {
                    uint32_t pointer = 0;
                    if (address > UINT32_MAX - region->pointer_offset[hop] ||
                        !native_animation_read(address + region->pointer_offset[hop], (unsigned char *)&pointer, sizeof pointer)) {
                        address = 0; break;
                    }
                    if (pointer == 0) { address = 0; null_target = 1; break; }
                    address = pointer;
                }
            }
            if (null_target) continue; /* Null is valid input state; the pointer field itself is captured elsewhere. */
            if (address == 0 || address > UINT32_MAX - region->offset) { fputs(" 0:-", capdiff_file); continue; }
            address += region->offset;
        }
        if (region->indirect) {
            if (region->argument_base) goto capdiff_region_resolved;
            uint32_t pointer = 0;
            if (!native_animation_read(region->address, (unsigned char *)&pointer, sizeof pointer) || pointer > UINT32_MAX - region->offset) { fputs(" 0:-", capdiff_file); continue; }
            address = pointer + region->offset;
        }
capdiff_region_resolved:
        if (length > sizeof bytes) length = (uint32_t)sizeof bytes;
        fprintf(capdiff_file, " %x:", address);
        if (address != 0u && address <= UINT32_MAX - length && native_animation_read(address, bytes, length)) {
            for (uint32_t byte = 0; byte < length; byte++) fprintf(capdiff_file, "%02x", bytes[byte]);
        } else {
            fputc('-', capdiff_file); /* unreadable region: ingest marks the case unusable */
        }
    }
    fputc('\n', capdiff_file);
    funlockfile(capdiff_file);
}
/* T3634: opt-in one-replay shadow execution for lane roots named by the
 * capdiff spec. The watched regions are the declared boundary: both bodies
 * receive the same bytes, then registers and those bytes are compared. */
extern bool kernel_guest_write_bytes(uint32_t address, const void *data, size_t length) __attribute__((weak));
typedef struct {
    uint32_t regs[8];
    uint32_t stack[8];
    uint32_t addresses[CAPDIFF_REGIONS_MAX];
    unsigned char *regions[CAPDIFF_REGIONS_MAX];
    const capdiff_root *root;
} shadow_entry;
static FILE *shadow_file;
static int shadow_on = -1;
static unsigned long long shadow_calls;
static int shadow_first_reported;
static void shadow_summary(void)
{
    if (shadow_file == NULL) return;
    flockfile(shadow_file);
    fprintf(shadow_file, "SHADOW_SUMMARY compared=%llu first_divergence=%s\n", shadow_calls,
            shadow_first_reported ? "yes" : "no");
    funlockfile(shadow_file);
}
static bool shadow_enabled(void)
{
    if (shadow_on < 0) {
        const char *path = getenv("TSFP_RUST_SHADOW_LOG");
        const char *enabled = getenv("TSFP_RUST_SHADOW");
        shadow_on = path != NULL && enabled != NULL && strcmp(enabled, "0") != 0 &&
                    strcmp(enabled, "off") != 0 && (shadow_file = fopen(path, "w")) != NULL;
        if (shadow_file != NULL) {
            setvbuf(shadow_file, NULL, _IOLBF, 0);
            (void)atexit(shadow_summary);
        }
    }
    return shadow_on != 0;
}
static shadow_entry *shadow_begin(uint32_t va)
{
    if (!shadow_enabled() || kernel_guest_write_bytes == NULL) return NULL;
    const capdiff_root *root = capdiff_find(va);
    if (root == NULL) return NULL;
    shadow_entry *entry = calloc(1u, sizeof *entry);
    if (entry == NULL) return NULL;
    entry->root = root;
    entry->regs[0] = g_eax; entry->regs[1] = g_ecx; entry->regs[2] = g_edx; entry->regs[3] = g_ebx;
    entry->regs[4] = g_esi; entry->regs[5] = g_edi; entry->regs[6] = g_ebp; entry->regs[7] = g_esp;
    if (g_esp > UINT32_MAX - sizeof entry->stack || !native_animation_read(g_esp, (unsigned char *)entry->stack, sizeof entry->stack)) {
        free(entry); return NULL;
    }
    for (uint32_t i = 0; i < root->count; i++) {
        const uint32_t length = root->regions[i].length;
        const capdiff_region *region = &root->regions[i];
        const uint32_t base = region->base_kind == 1u ? entry->regs[0] :
                              region->base_kind == 2u ? entry->stack[region->base_index] : region->address;
        if (base == 0u || base > UINT32_MAX - length) goto fail;
        entry->addresses[i] = base;
        if (length == 0u || length > CAPDIFF_REGION_BYTES) goto fail;
        entry->regions[i] = malloc(length);
        if (entry->regions[i] == NULL || !native_animation_read(base, entry->regions[i], length)) goto fail;
    }
    return entry;
fail:
    for (uint32_t i = 0; i < root->count; i++) free(entry->regions[i]);
    free(entry);
    return NULL;
}
static void shadow_restore(const shadow_entry *entry)
{
    if (!kernel_guest_write_bytes(entry->regs[7], entry->stack, sizeof entry->stack))
        tsfp_bridge_fail(HOST_STOP_BRIDGE_CONTRACT, entry->root->va, entry->regs[7], g_esp, "shadow could not restore guest stack");
    for (uint32_t i = 0; i < entry->root->count; i++)
        if (!kernel_guest_write_bytes(entry->addresses[i], entry->regions[i], entry->root->regions[i].length))
            tsfp_bridge_fail(HOST_STOP_BRIDGE_CONTRACT, entry->root->va, entry->regs[7], g_esp, "shadow could not restore watched guest region");
    g_eax = entry->regs[0]; g_ecx = entry->regs[1]; g_edx = entry->regs[2]; g_ebx = entry->regs[3];
    g_esi = entry->regs[4]; g_edi = entry->regs[5]; g_ebp = entry->regs[6]; g_esp = entry->regs[7];
}
static void shadow_finish(shadow_entry *entry, void (*lifted)(void), const rust_lane_cpu *rust)
{
    if (entry == NULL) return;
    uint32_t rust_stack[8] = {0};
    const bool rust_stack_readable = native_animation_read(entry->regs[7], (unsigned char *)rust_stack, sizeof rust_stack);
    unsigned char *rust_bytes[CAPDIFF_REGIONS_MAX] = {0};
    bool readable = true;
    for (uint32_t i = 0; i < entry->root->count; i++) {
        rust_bytes[i] = malloc(entry->root->regions[i].length);
        if (rust_bytes[i] == NULL || !native_animation_read(entry->addresses[i], rust_bytes[i], entry->root->regions[i].length)) readable = false;
    }
    const uint32_t rust_regs[8] = {rust->eax, rust->ecx, rust->edx, rust->ebx, rust->esi, rust->edi, rust->ebp, rust->esp};
    shadow_restore(entry);
    const uint32_t entry_esp = entry->regs[7];
    lifted();
    const uint32_t lifted_boundary = lane_lifted_boundary(entry->root->va, entry_esp,
        lane_pops(entry->root->va), "shadow lifted body left an unexpected ESP");
    /* Compare at the bridge boundary, before the generated adapter performs
     * its own cleanup. 0x29e40 retains one argument pop at this boundary. */
    const uint32_t lifted_regs[8] = {g_eax, g_ecx, g_edx, g_ebx, g_esi, g_edi, g_ebp, lifted_boundary};
    uint32_t lifted_stack[8] = {0};
    const bool lifted_stack_readable = native_animation_read(entry->regs[7], (unsigned char *)lifted_stack, sizeof lifted_stack);
    bool mismatch = !readable || !rust_stack_readable || !lifted_stack_readable;
    unsigned char *lifted_bytes[CAPDIFF_REGIONS_MAX] = {0};
    for (uint32_t i = 0; i < entry->root->count; i++) {
        const uint32_t length = entry->root->regions[i].length;
        lifted_bytes[i] = malloc(length);
        if (lifted_bytes[i] == NULL || !native_animation_read(entry->addresses[i], lifted_bytes[i], length)) { mismatch = true; continue; }
        if (rust_bytes[i] != NULL) for (uint32_t j = 0; j < length; j++) if (rust_bytes[i][j] != lifted_bytes[i][j]) {
            mismatch = true; break;
        }
    }
    for (unsigned i = 0; i < 8u; i++) if (rust_regs[i] != lifted_regs[i]) mismatch = true;
    /* Stack slot zero is the return-address slot consumed by the lifted call.
     * Compare argument slots, while pointer-referenced outputs are covered by
     * the explicitly watched regions. */
    for (unsigned i = 1; i < 8u; i++) if (rust_stack[i] != lifted_stack[i]) mismatch = true;
    const unsigned long long ordinal = __atomic_fetch_add(&shadow_calls, 1ull, __ATOMIC_RELAXED) + 1ull;
    if (mismatch) {
        if (__atomic_exchange_n(&shadow_first_reported, 1, __ATOMIC_RELAXED) == 0) {
            flockfile(shadow_file);
            fprintf(shadow_file, "FIRST_DIVERGENCE root=%08x poll=%llu call=%llu args=%08x,%08x,%08x,%08x ",
                    entry->root->va, (unsigned long long)tsfp_input_host_poll_count(0u), ordinal,
                    entry->stack[1], entry->stack[2], entry->stack[3], entry->stack[4]);
            for (unsigned i = 0; i < 8u; i++) if (rust_regs[i] != lifted_regs[i])
                fprintf(shadow_file, "reg%u rust=%08x lifted=%08x ", i, rust_regs[i], lifted_regs[i]);
            for (unsigned i = 1; i < 8u; i++) if (rust_stack[i] != lifted_stack[i])
                fprintf(shadow_file, "stack%u@%08x rust=%08x lifted=%08x ", i, entry->regs[7] + i * 4u, rust_stack[i], lifted_stack[i]);
            if (!readable) fprintf(shadow_file, "watched-memory=unreadable ");
            for (uint32_t i = 0; i < entry->root->count; i++) {
                if (rust_bytes[i] == NULL || lifted_bytes[i] == NULL) continue;
                for (uint32_t j = 0; j < entry->root->regions[i].length; j++) {
                    if (rust_bytes[i][j] != lifted_bytes[i][j]) {
                        fprintf(shadow_file, "mem[%08x+%x]=%02x/%02x ", entry->addresses[i], j,
                                rust_bytes[i][j], lifted_bytes[i][j]);
                        break;
                    }
                }
            }
            fputc('\n', shadow_file);
            funlockfile(shadow_file);
        }
    }
    /* Leave lifted registers and RAM authoritative for the remainder of the replay. */
    g_esp = lifted_boundary;
    for (uint32_t i = 0; i < entry->root->count; i++) { free(entry->regions[i]); free(rust_bytes[i]); free(lifted_bytes[i]); }
    free(entry);
}
static int game_rust_try_body(uint32_t va, int *rust_path);
static int game_rust_try_traced(uint32_t va, int *rust_path)
{
    uint32_t args[4] = {0};
    const uint32_t entry_esp = g_esp; /* T3702: call-time ESP, recorded on the entry and exit rows */
    const bool traced = call_args_wants(va) && g_esp <= UINT32_MAX - 20u && native_animation_read(g_esp + 4u, (unsigned char *)args, sizeof args);
    if (traced) call_args_row(va, 0u, 0u, 0u, args, g_esp);
    const capdiff_root *capdiff = capdiff_find(va);
    if (capdiff != NULL) capdiff_row(capdiff);
    const int taken = game_rust_try_body(va, rust_path);
    if (traced && taken && lane_pops(va) >= 0) call_args_row(va, 1u, g_eax, call_args_st0(), args, entry_esp);
    return taken;
}
static int game_rust_try_body(uint32_t va, int *rust_path);
static int game_rust_try_impl(uint32_t va, int *rust_path)
{
    uint32_t args[4], frame;
    const bool relevant = native_animation_enabled() && tsfp_rt_animation_wants_root != NULL && tsfp_rt_animation_wants_root(va) != 0u;
    const bool observe = relevant && tsfp_rt_animation_note != NULL && g_esp <= UINT32_MAX - 20u &&
        native_animation_read(g_esp + 4u, (unsigned char *)args, sizeof args) &&
        native_animation_read(0x6B7AF0u, (unsigned char *)&frame, sizeof frame);
    if (observe) tsfp_rt_animation_note(0u, va, args[0], args[1], args[2], args[3], frame, native_animation_read);
    const int taken = game_rust_try_traced(va, rust_path);
    if (observe) tsfp_rt_animation_note(1u, va, args[0], args[1], args[2], args[3], frame, native_animation_read);
    return taken;
}
static int game_rust_try_body(uint32_t va, int *rust_path);
static bool tsfp_memory_try(uint32_t va, rust_registers *registers, uintptr_t offset)
{
    return tsfp_memory_abi_try != NULL && tsfp_memory_abi_try(va, registers, offset);
}
static int game_rust_try_body(uint32_t va, int *rust_path)
{
    shadow_root *shadowed_root = shadow_find(va);
    if (shadowed_root != NULL) {
        void (*body)(void) = original(va);
        if (body == NULL) return 0;
        return shadow_try_leaf(shadowed_root, body, rust_path);
    }
    if (is_ext_root(va)) {
        const int taken = rust_ext_try != NULL && rust_ext_try(va);
        /* I-T3398-20: an ext root that is also a lane root (0x1C8540 since the T3398 math roots) has an abort-only lifted
         * wrapper, its body is tsfp_original_<va>. Returning 0 when the ext bridge declines aborted every replay, so the
         * declined call falls through to the lane path below (Rust lane when selected, else the retained original). */
        if (taken || lane_pops(va) < 0) { *rust_path = taken; return taken; }
    }
    void (*lifted)(void) = original(va);
    if (lifted == NULL) return 0;
    const int pops = lane_pops(va);
    if (pops >= 0) {
        /* T1858: lane root, the whole register file crosses the boundary and ESP comes back. */
        rust_lane_cpu cpu = {g_eax, g_ecx, g_edx, g_ebx, g_esi, g_edi, g_ebp, g_esp};
        shadow_entry *shadow = shadow_begin(va);
#ifdef TSFP_HAVE_WEAPON_ROOTS
        const bool taken = tsfp_rust_is_weapon_root(va) ? tsfp_rust_try_weapon(va, &cpu, (uintptr_t)g_xbox_mem_offset)
                                                        : tsfp_rust_try_lane(va, &cpu, (uintptr_t)g_xbox_mem_offset);
#else
        const bool taken = tsfp_rust_try_lane(va, &cpu, (uintptr_t)g_xbox_mem_offset);
#endif
#ifdef TSFP_TEST_REAL_ORIGINALS
        /* Test-only fault injection: corrupt the Rust return register before the
         * shadow comparison, then prove the lifted value remains authoritative. */
        if (getenv("TSFP_RUST_SHADOW_TEST_SEED_MISMATCH") != NULL) cpu.eax ^= 1u;
#endif
        if (taken && shadow != NULL) {
            shadow_finish(shadow, lifted, &cpu);
            *rust_path = 0; /* the comparison ran both; lifted remains the authoritative result */
            return 1;
        }
        if (!taken && shadow != NULL) {
            for (uint32_t i = 0; i < shadow->root->count; i++) free(shadow->regions[i]);
            free(shadow);
        }
        if (!taken) {
            const uint32_t entry_esp = g_esp;
            lifted();
            g_esp = lane_lifted_boundary(va, entry_esp, pops, "lane root original left an unexpected ESP");
#ifdef TSFP_HAVE_WEAPON_ROOTS
            /* T3398: retain the lifted D01C0 return and its two ABI output vectors as the
             * trace reference. This read-only observer does not alter guest registers or RAM. */
            if (va == 0x000D01C0u && tsfp_player_interaction_trace_reference != NULL &&
                entry_esp <= UINT32_MAX - 12u) {
                uint32_t pointers[2], words[7];
                if (native_animation_read(entry_esp + 4u, (unsigned char *)pointers, sizeof pointers) &&
                    native_animation_read(pointers[0], (unsigned char *)&words[1], 3u * sizeof(uint32_t)) &&
                    native_animation_read(pointers[1], (unsigned char *)&words[4], 3u * sizeof(uint32_t))) {
                    words[0] = g_eax;
                    tsfp_player_interaction_trace_reference(words, 7u);
                }
            }
#endif
            *rust_path = 0;
            return 1;
        }
        g_eax = cpu.eax; g_ecx = cpu.ecx; g_edx = cpu.edx; g_ebx = cpu.ebx;
        g_esi = cpu.esi; g_edi = cpu.edi; g_ebp = cpu.ebp; g_esp = cpu.esp;
        *rust_path = 1;
        return 1;
    }
    rust_registers state = {g_eax, g_ecx, g_edx, g_esp};
    if (!tsfp_rust_try(va, &state, (uintptr_t)g_xbox_mem_offset)
        && !tsfp_memory_try(va, &state, (uintptr_t)g_xbox_mem_offset)) {
        const uint32_t entry_esp = g_esp;
        lifted();
        /* Arena advance is stdcall(1); the outer adapter owns cleanup. */
        const uint32_t cleanup = va == 0x003bb710u ? 8u : 4u;
        if (g_esp != entry_esp + cleanup) tsfp_bridge_fail(HOST_STOP_BRIDGE_CONTRACT, va, entry_esp, g_esp, "root original left an unexpected ESP");
        g_esp = entry_esp;
        *rust_path = 0;
        return 1;
    }
    g_eax = state.eax; g_ecx = state.ecx; g_edx = state.edx;
    *rust_path = 1;
    return 1;
}

