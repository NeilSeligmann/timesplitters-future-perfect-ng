/* T3833 live targeted capture (play.sh --capture-targets): a Rust root on the capture ALLOW list runs its lifted body,
 * so the capture sees the original; every other root keeps the selection. Weapon and ext roots are not reselected. */
bool t2cap_targets_active(void);
bool t2cap_target_listed(uint32_t va);
/* Roots another host subsystem requires selected (each has a "requires --rust-ports to select"
 * check below). The capture host never swaps them back to the lifted original, or that subsystem
 * refuses to start (I-T3866-1: --rust-rea-ai and the reach target set). */
static const uint32_t CAPTURE_ANCHOR_ROOTS[] = {0x266250u};

static bool capture_anchor_root(uint32_t va)
{
    for (size_t i = 0; i < sizeof CAPTURE_ANCHOR_ROOTS / sizeof CAPTURE_ANCHOR_ROOTS[0]; i++) {
        if (CAPTURE_ANCHOR_ROOTS[i] == va) return true;
    }
    return false;
}

static bool capture_targets_lifted(const char *pilot)
{
    if (!t2cap_targets_active() || strcmp(pilot, "off") == 0) return true;
    size_t cap = strlen(pilot) + 1u, used = strlen(pilot);
    char *spec = malloc(cap);
    if (spec == NULL) return false;
    memcpy(spec, pilot, cap);
    unsigned excluded = 0u;
    for (size_t r = 0; r < 65536u; r++) {
        const uint32_t va = tsfp_rust_root(r);
        if (va == 0u) break;
        if (!t2cap_target_listed(va) || capture_anchor_root(va)) continue;
        if (used + 16u >= cap) {
            cap = cap * 2u + 64u;
            char *grown = realloc(spec, cap);
            if (grown == NULL) { free(spec); return false; }
            spec = grown;
        }
        used += (size_t)snprintf(spec + used, cap - used, ",-0x%x", va);
        excluded++;
    }
    const bool ok = excluded == 0u || tsfp_rust_configure((const unsigned char *)spec, used);
    if (ok) printf("rust ports     %u capture-target roots run their lifted originals (T3833)\n", excluded);
    free(spec);
    return ok;
}
