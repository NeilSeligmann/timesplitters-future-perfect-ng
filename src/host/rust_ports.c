bool host_rust_shadow_configure(const char *spec, uint32_t promote)
{
    if (spec == NULL) return true;
#ifdef TSFP_RUST_PORTS
    if (promote == 0u || shadow_leaf_execute == NULL || shadow_denylist_contains == NULL ||
        shadow_denylist_add == NULL || strcmp(spec, "all") == 0) return false;
    const char *cursor = spec;
    while (*cursor != '\0') {
        char *end;
        unsigned long va = strtoul(cursor, &end, 16);
        if (end == cursor || va > UINT32_MAX || (*end != '\0' && *end != ',')) return false;
        shadow_root *root = NULL;
        for (size_t i = 0; i < sizeof shadow_roots / sizeof shadow_roots[0]; ++i)
            if (shadow_roots[i].va == (uint32_t)va) root = &shadow_roots[i];
        if (root == NULL || root->enabled) return false;
        int denied = shadow_denylist_contains(shadow_denylist_path, root->va);
        if (denied < 0) return false;
        root->policy.promote_at = promote;
        root->enabled = true;
        if (denied) shadow_policy_disable(&root->policy);
        if (*end == '\0') return true;
        cursor = end + 1;
        if (*cursor == '\0') return false;
    }
    return false;
#else
    (void)promote;
    return false;
#endif
}
bool host_rust_shadow_stats(uint32_t va, uint64_t *clean, uint64_t *diff, bool *promoted,
                            uint64_t *calls, uint64_t *unavailable)
{
#ifdef TSFP_RUST_PORTS
    shadow_root *root = shadow_find(va);
    if (root == NULL || clean == NULL || diff == NULL || promoted == NULL || calls == NULL || unavailable == NULL) return false;
    shadow_policy_lock(&root->policy);
    *clean = root->policy.clean;
    *diff = root->policy.diff;
    *promoted = root->policy.promoted && !root->policy.disabled;
    shadow_policy_unlock(&root->policy);
    *calls = __atomic_load_n(&root->calls, __ATOMIC_RELAXED);
    *unavailable = __atomic_load_n(&root->unavailable, __ATOMIC_RELAXED);
    return true;
#else
    (void)va; (void)clean; (void)diff; (void)promoted; (void)calls; (void)unavailable;
    return false;
#endif
}
bool host_rust_ports_configure(const char *spec)
{
#ifdef TSFP_RUST_PORTS
    /* Split the list: ext roots (opt-in, never selected by `all`) go to the ext bridge,
     * everything else to the integer pilot selection. */
    /* T1976: 4096 so that a bisect probe naming several hundred roots (9 characters each) fits. */
    char pilot[4096] = "", ext[256] = "", weapon[2048] = "";
    if (strlen(spec) >= sizeof pilot) return false;
    /* T2305: `all` also selects the c2r settings roots (lane word `settings`), `-settings` drops them again. */
    bool all_settings = false, no_settings = false;
    for (const char *start = spec;;) {
        const char *comma = strchr(start, ',');
        const size_t length = comma != NULL ? (size_t)(comma - start) : strlen(start);
        if (length == 0u || length >= 32u) return false; /* empty tokens stay invalid, as before */
        char token[32];
        memcpy(token, start, length);
        token[length] = '\0';
        char *end = NULL;
        const unsigned long va = strtoul(token, &end, 16);
        if (strcmp(token, "-settings") == 0) { no_settings = true; if (comma == NULL) break; start = comma + 1; continue; }
        if (strcmp(token, "all") == 0) all_settings = true;
        char *list = (*end == '\0' && is_ext_root((uint32_t)va)) ? ext : pilot;
#ifdef TSFP_HAVE_WEAPON_ROOTS
        if (strcmp(token, "weapons") == 0 || strcmp(token, "player") == 0 ||
            strcmp(token, "settings") == 0 || strcmp(token, "player-interaction") == 0 ||
            strcmp(token, "pickup-tick") == 0 ||
            (*end == '\0' && tsfp_rust_is_weapon_root((uint32_t)va))) list = weapon;
#endif
        if (list[0] != '\0') strcat(list, ",");
        strcat(list, token);
        if (comma == NULL) break;
        start = comma + 1;
    }
#ifdef TSFP_HAVE_WEAPON_ROOTS
    if (all_settings && !no_settings) {
        if (weapon[0] != '\0') strcat(weapon, ",");
        strcat(weapon, "settings");
    }
#else
    (void)all_settings; (void)no_settings;
#endif
    if (ext[0] == '\0') strcpy(ext, "off");
    if (pilot[0] == '\0') strcpy(pilot, "off");
    if (weapon[0] == '\0') strcpy(weapon, "off");
#ifdef TSFP_HAVE_WEAPON_ROOTS
    if (!tsfp_rust_weapon_configure((const unsigned char *)weapon, strlen(weapon))) return false;
#else
    if (strcmp(weapon, "off") != 0) return false;
#endif
    const bool ok = (host_rust_ext_configure != NULL ? host_rust_ext_configure(ext) : strcmp(ext, "off") == 0) &&
                    tsfp_rust_configure((const unsigned char *)pilot, strlen(pilot));
#ifdef TSFP_T2_CAPTURE_HOST
    if (ok && !capture_targets_lifted(pilot)) return false;
#endif
    if (ok) printf("rust ports     %s (original-verified integer pilot; ext roots %s, opt-in, unadmitted)\n", spec, ext);
    return ok;
#else
    return strcmp(spec, "off") == 0;
#endif
}

